def tier_effects(s, n):
    """grow / ease / remove effects for a tiered spirit wif_eng_<s>_1..n."""
    ids = [f'wif_eng_{s}_{t}' for t in range(1, n + 1)]
    grow = [f'{"if" if i == 0 else "else_if"} = {{ limit = {{ has_idea = {a} }} swap_ideas = {{ remove_idea = {a} add_idea = {b} }} }}'
            for i, (a, b) in enumerate(zip(ids, ids[1:]))]
    grow.append(f'else_if = {{ limit = {{ NOT = {{ {" ".join(f"has_idea = {i}" for i in ids)} }} }} add_ideas = {ids[0]} }}')
    ease = [f'{"if" if i == 0 else "else_if"} = {{ limit = {{ has_idea = {b} }} swap_ideas = {{ remove_idea = {b} add_idea = {a} }} }}'
            for i, (a, b) in enumerate(reversed(list(zip(ids, ids[1:]))))]
    ease.append(f'else_if = {{ limit = {{ has_idea = {ids[0]} }} remove_ideas = {ids[0]} }}')
    rm = [f'if = {{ limit = {{ has_idea = {i} }} remove_ideas = {i} }}' for i in ids]
    return (f'wif_eng_{s}_grow = {{\n' + indent('\n'.join(grow), 1) + '\n}\n'
            f'wif_eng_{s}_ease = {{\n' + indent('\n'.join(ease), 1) + '\n}\n'
            f'wif_eng_{s}_remove = {{\n' + indent('\n'.join(rm), 1) + '\n}\n')


