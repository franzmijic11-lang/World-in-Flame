    for s, (pic, tiers, _, _) in SPIRITS.items():
        for t, mods in enumerate(tiers, 1):
            o += [f'\t\twif_eng_{s}_{t} = {{', f'\t\t\tpicture = {pic}', '\t\t\tallowed = { always = no }',
                  '\t\t\tallowed_civil_war = { always = yes }', '\t\t\tremoval_cost = -1', '\t\t\tmodifier = {']
            o += [f'\t\t\t\t{a} = {b}' for a, b in mods.items()]
            o += ['\t\t\t}', '\t\t}']
    for k, (pic, mods, _, _) in IDEAS.items():
        o += [f'\t\t{k} = {{', f'\t\t\tpicture = {pic}', '\t\t\tallowed = { always = no }',
              '\t\t\tallowed_civil_war = { always = yes }', '\t\t\tremoval_cost = -1', '\t\t\tmodifier = {']
        o += [f'\t\t\t\t{a} = {b}' for a, b in mods.items()]
        o += ['\t\t\t}', '\t\t}']
    o += ['\t}', '}', '']
    write('common/ideas/wif_eng_protektorat_ideas.txt', '\n'.join(o))
    o = [HEADER.rstrip('\n'), 'opinion_modifiers = {']
    for k, (v, _) in OPINION.items():
        o += [f'\t{k} = {{', f'\t\tvalue = {v}', '\t}']
    write('common/opinion_modifiers/wif_eng_protektorat_opinion_modifiers.txt', '\n'.join(o + ['}', '']))


