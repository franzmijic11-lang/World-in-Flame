def patch_coup():
    path = p('events', 'wif_ger_abroad.txt')
    raw = open(path, 'rb').read()
    s = raw.decode('utf-8-sig')
    bom = raw.startswith(b'\xef\xbb\xbf')
    nl = '\r\n' if '\r\n' in s else '\n'
    if 'wif_eng_watch_the_generals' in s:
        print('coup already patched')
        return
    old = ('\t\tname = wif_ger_abroad.2.a' + nl + '\t\tai_chance = { base = 90 }' + nl)
    assert s.count(old) == 1, s.count(old)
    new = ('\t\tname = wif_ger_abroad.2.a' + nl + '\t\tai_chance = {' + nl + '\t\t\tbase = 90' + nl +
           '\t\t\t# Watch the Generals (tools/gen_eng_protektorat_tree.py): 90% -> 30%' + nl +
           '\t\t\tmodifier = {' + nl + '\t\t\t\tfactor = 0.0476' + nl +
           '\t\t\t\tENG = { has_country_flag = wif_eng_watch_the_generals }' + nl + '\t\t\t}' + nl + '\t\t}' + nl)
    s = s.replace(old, new)
    open(path, 'wb').write((b'\xef\xbb\xbf' if bom else b'') + s.encode('utf-8'))
    print('patched the American coup chance')


def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


def gen_loc(m):
    o = ['l_english:']
    for f in m['focuses']:
        flav = re.split(r'\n\n(?:Effect:|Requires|Available|Starting spirits)', f['desc'])[0].strip()
        o += [f' {f["fid"]}:0 "{esc(f["name"])}"', f' {f["fid"]}_desc:0 "{esc(flav)}"']
    for s, (_, tiers, name, desc) in SPIRITS.items():
        for t in range(1, len(tiers) + 1):
            o += [f' wif_eng_{s}_{t}:0 "{esc(name + TIER_SUFFIX[t - 1])}"', f' wif_eng_{s}_{t}_desc:0 "{esc(desc)}"']
    for k, (_, _, name, desc) in IDEAS.items():
        o += [f' {k}:0 "{esc(name)}"', f' {k}_desc:0 "{esc(desc)}"']
    for k, (_, name) in OPINION.items():
        o.append(f' {k}:0 "{esc(name)}"')
    o += [f' {k}:0 "{v}"' for k, v in TOOLTIPS.items()]
    write('localisation/english/wif_eng_protektorat_tree_l_english.yml', '\n'.join(o) + '\n', bom=True, crlf=False)


