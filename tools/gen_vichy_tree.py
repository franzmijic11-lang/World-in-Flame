def leader(name, portrait, party=None):
    """party None: the leader takes the ruling party's ideology."""
    if party:
        return j(f'set_politics = {{ ruling_party = {party} elections_allowed = no }}',
                 'create_country_leader = {', f'\tname = "{name}"', f'\tpicture = "{portrait}"', '\texpire = "1975.1.1"',
                 f'\tideology = {SUBS[party]}', '\ttraits = { }', '}')
    o = []
    first = True
    for party_, sub in SUBS.items():
        o += [f'{"if" if first else "else_if"} = {{', f'\tlimit = {{ has_government = {party_} }}',
              '\tcreate_country_leader = {', f'\t\tname = "{name}"', f'\t\tpicture = "{portrait}"',
              '\t\texpire = "1975.1.1"', f'\t\tideology = {sub}', '\t\ttraits = { }', '\t}', '}']
        first = False
    return '\n'.join(o)


