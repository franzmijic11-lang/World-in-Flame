"""Vichy France - Welt in Flammen's replacement for vanilla's vichy_french_focus.

Source of truth for everything main() writes. Run:

    python tools/gen_vichy_tree.py

Layout, names, durations and prerequisites come from the Focus Tree Planner
(map doc `vic-wif`), snapshotted in tools/planner_vic.json - re-snapshot after
editing the planner. Rewards live in R below, keyed by fid minus wif_vic_.

The tree keeps vanilla's id (vichy_french_focus) and overrides vanilla's
common/national_focus/vichy_france.txt BY FILENAME, so every vanilla path that
loads the Vichy tree (france.14, the test decision) loads this one.

Design (the user's spec, 2026-11-09):
  - Vichy starts as a German satellite (common/scripted_effects/
    wif_vichy_effects.txt, called from events/France.txt).
  - Wartime half: the French State, keeping the Empire together, collaboration.
    Those focuses close when the war in the west is won.
  - Post-victory half: Germany hands most of France back, the economy, the
    succession to Petain, the SS requisition of the EAST (Franche-Comte,
    Champagne, Picardy - GER_requisition_territory_from_our_french_puppet) and
    SS Burgundy if it appears.
  - Independence in the German civil war: Vichy stops being a subject but
    STAYS in the Axis. Burgundy is a choice: attack it (only if it has no
    nuclear weapons - the AI included) or leave it be.
"""
