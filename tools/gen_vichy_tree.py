def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


def gen_loc(m):
    o = ['l_english:']
    for f in m['focuses']:
        flav = re.split(r'\n\n(?:Effect:|Requires|Available|Vichy starts)', f['desc'])[0].strip()
        o.append(f' {f["fid"]}:0 "{esc(f["name"])}"')
        o.append(f' {f["fid"]}_desc:0 "{esc(flav)}"')
    for k, (_, _, name, desc) in IDEAS.items():
        o.append(f' {k}:0 "{esc(name)}"')
        o.append(f' {k}_desc:0 "{esc(desc)}"')
    for k, (_, name) in OPINION.items():
        o.append(f' {k}:0 "{esc(name)}"')
    for k, v in TOOLTIPS.items():
        o.append(f' {k}:0 "{v}"')
    write('localisation/english/wif_vichy_l_english.yml', '\n'.join(o) + '\n', bom=True, crlf=False)


