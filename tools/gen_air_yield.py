"""Allied AI air forces yield crowded airfields to players.

Writes, from the map (WiF's overrides first, vanilla for the rest):
  * common/scripted_effects/wif_air_yield_auto.txt - wif_air_yield_update,
    run weekly for each player, and one effect per strategic region
  * common/ai_strategy/wif_air_yield_auto.txt - one strategy per region that
    tells an AI to pull its planes out (strategic_air_importance -500000, the
    value Frontline AI uses to evacuate regions)

The hand-written helpers (plane counting, the ally test) live in
common/scripted_effects/wif_air_yield.txt and
common/scripted_triggers/wif_air_yield_triggers.txt.

Rerun after moving provinces between states or regions:
    python tools/gen_air_yield.py
"""
import os
import re

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = r"C:/Program Files (x86)/Steam/steamapps/common/Hearts of Iron IV"

EFFECTS_FILE = os.path.join(MOD, 'common', 'scripted_effects', 'wif_air_yield_auto.txt')
STRATEGY_FILE = os.path.join(MOD, 'common', 'ai_strategy', 'wif_air_yield_auto.txt')

# Each air base level holds this many planes (NDefines.NAir.AIRBASE_CAPACITY_MULT,
# not changed by WiF or UTTNH).
PLANES_PER_LEVEL = 200
CROWDED = 0.9       # a region is crowded at 90% of its capacity
RELEASED = 0.7      # and stays crowded until it falls under 70%
YIELD_VALUE = -500000


def merged_files(sub):
    """Files of a folder, WiF's overriding vanilla's by file name."""
    files = {}
    for root in (GAME, MOD):
        d = os.path.join(root, sub)
        if os.path.isdir(d):
            for f in os.listdir(d):
                if f.endswith('.txt'):
                    files[f] = os.path.join(d, f)
    return sorted(files.values())


def read(path):
    with open(path, encoding='utf-8-sig', errors='replace') as fh:
        return re.sub(r'#[^\n]*', '', fh.read())


def provinces_block(text):
    m = re.search(r'\bprovinces\s*=\s*\{([^}]*)\}', text)
    return [int(x) for x in m.group(1).split()] if m else []


def main():
    prov_region = {}
    for path in merged_files('map/strategicregions'):
        text = read(path)
        rid = int(re.search(r'\bid\s*=\s*(\d+)', text).group(1))
        for p in provinces_block(text):
            prov_region[p] = rid

    region_states = {}
    for path in merged_files('history/states'):
        text = read(path)
        m = re.search(r'\bstate\s*=\s*\{', text)
        if not m:
            continue
        sid = int(re.search(r'\bid\s*=\s*(\d+)', text[m.end():]).group(1))
        votes = {}
        for p in provinces_block(text[m.end():]):
            r = prov_region.get(p)
            if r is not None:
                votes[r] = votes.get(r, 0) + 1
        if votes:
            # A state lying across a region border goes with most of it. Its
            # air base counts towards that region only - the engine places
            # the base in one province, and this is the best guess at which.
            r = max(votes, key=votes.get)
            region_states.setdefault(r, []).append(sid)

    regions = sorted(region_states)
    E = ['# GENERATED by tools/gen_air_yield.py - do not edit by hand.',
         '# See common/scripted_effects/wif_air_yield.txt for how this works.',
         '']
    U = ['# Player scope, weekly from on_weekly. Last in the file so every',
         '# region effect it calls is already defined.',
         'wif_air_yield_update = {',
         '\twif_air_build_friends = yes']
    U += [f'\twif_air_yield_region_{r} = yes' for r in regions]
    U += ['\tclear_variable = wif_air_cap', '\tclear_variable = wif_air_used',
          '\tclear_variable = wif_air_region', '\tclear_variable = wif_air_probe',
          '\tclear_variable = wif_air_step', '\tclear_variable = wif_air_count',
          '\tclear_array = wif_air_friends', '}', '']

    hi = PLANES_PER_LEVEL * CROWDED
    lo = PLANES_PER_LEVEL * RELEASED
    for r in regions:
        E += [f'wif_air_yield_region_{r} = {{',
              '\tset_variable = { wif_air_cap = 0 }']
        for s in sorted(region_states[r]):
            E += [f'\t{s} = {{ if = {{ limit = {{ air_base > 0 controller = {{ wif_air_friend_of_root = yes }} }} '
                  f'add_to_variable = {{ ROOT.wif_air_cap = building_level@air_base }} }} }}']
        E += ['\tif = {',
              '\t\tlimit = { check_variable = { wif_air_cap > 0 } }',
              f'\t\tset_variable = {{ wif_air_region = {r} }}',
              '\t\twif_air_count_region = yes',
              f'\t\tset_temp_variable = {{ wif_air_hi = wif_air_cap }}',
              f'\t\tmultiply_temp_variable = {{ wif_air_hi = {hi:g} }}',
              f'\t\tset_temp_variable = {{ wif_air_lo = wif_air_cap }}',
              f'\t\tmultiply_temp_variable = {{ wif_air_lo = {lo:g} }}',
              '\t\tif = {',
              '\t\t\tlimit = { check_variable = { wif_air_used > wif_air_hi } }',
              f'\t\t\tif = {{ limit = {{ NOT = {{ has_country_flag = wif_air_crowded_{r} }} }} '
              f'set_country_flag = {{ flag = wif_air_hold_{r} days = 30 value = 1 }} '
              f'log = "WiF air yield: [ROOT.GetTag] region {r} crowded, [?wif_air_used|0] planes, '
              f'room for [?wif_air_cap|0] levels" }}',
              f'\t\t\tset_country_flag = wif_air_crowded_{r}',
              '\t\t}',
              '\t\telse_if = {',
              '\t\t\tlimit = {',
              '\t\t\t\tcheck_variable = { wif_air_used < wif_air_lo }',
              f'\t\t\t\tNOT = {{ has_country_flag = wif_air_hold_{r} }}',
              '\t\t\t}',
              f'\t\t\tif = {{ limit = {{ has_country_flag = wif_air_crowded_{r} }} '
              f'log = "WiF air yield: [ROOT.GetTag] region {r} released, [?wif_air_used|0] planes, '
              f'room for [?wif_air_cap|0] levels" }}',
              f'\t\t\tclr_country_flag = wif_air_crowded_{r}',
              '\t\t}',
              '\t}',
              '\telse = {',
              f'\t\tclr_country_flag = wif_air_crowded_{r}',
              f'\t\tclr_country_flag = wif_air_hold_{r}',
              '\t}',
              '\tif = {',
              f'\t\tlimit = {{ has_country_flag = wif_air_crowded_{r} }}',
              '\t\tfor_each_scope_loop = {',
              '\t\t\tarray = wif_air_friends',
              f'\t\t\tif = {{ limit = {{ is_ai = yes }} set_country_flag = {{ flag = wif_air_yield_{r} days = 10 value = 1 }} }}',
              '\t\t}',
              '\t}',
              '}',
              '']

    S = ['# GENERATED by tools/gen_air_yield.py - do not edit by hand.',
         '# See common/scripted_effects/wif_air_yield.txt for how this works.',
         '#',
         '# The flag is set for 10 days by a player\'s weekly pass and refreshed',
         '# while the region stays crowded, so it lapses by itself once it is',
         '# not - or once the AI is no longer that player\'s ally.',
         '']
    for r in regions:
        S += [f'wif_air_yield_{r} = {{',
              '\tallowed = { always = yes }',
              f'\tenable = {{ has_country_flag = wif_air_yield_{r} }}',
              '\tabort_when_not_enabled = yes',
              f'\tai_strategy = {{ type = strategic_air_importance id = {r} value = {YIELD_VALUE} }}',
              '}',
              '']

    E += U
    for path, lines in ((EFFECTS_FILE, E), (STRATEGY_FILE, S)):
        with open(path, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write('\n'.join(lines))
    print(f'{len(regions)} regions, {sum(len(v) for v in region_states.values())} states')


if __name__ == '__main__':
    main()
