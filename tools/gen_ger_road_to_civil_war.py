def validate():
    ids = [f.id for f in FOCUSES]
    assert len(ids) == len(set(ids)), 'duplicate ids'
    known = set(ids) | set(EXISTING_NAMES)
    cells = {}
    for f in FOCUSES:
        for p in f.pre + f.mx + f.after:
            assert p in known, (f.id, p)
        for m in f.mx:
            assert f.id in next(g for g in FOCUSES if g.id == m).mx, ('one-sided mx', f.id, m)
        assert (f.x, f.y) not in cells, ('cell taken', f.id, cells.get((f.x, f.y)))
        cells[(f.x, f.y)] = f.id
        if f.who:
            assert f.who in CHAR, f.who
    # icons must exist, ids must not clash with any other German focus
    icons = set()
    for root in (GAME, MOD):
        d = os.path.join(root, 'interface')
        for fn in os.listdir(d):
            if fn.endswith('.gfx'):
                icons |= set(re.findall(r'name\s*=\s*"?(GFX_[A-Za-z0-9_]+)', open(os.path.join(d, fn), encoding='utf-8', errors='replace').read()))
    bad = [(f.id, f.icon) for f in FOCUSES if f.icon not in icons]
    assert not bad, bad
    others = set()
    for root in (GAME, MOD):
        d = os.path.join(root, 'common', 'national_focus')
        for fn in os.listdir(d):
            if root == MOD and fn == 'wif_ger_victory.txt':
                continue
            others |= set(re.findall(r'\bid\s*=\s*(GER_\w+)', open(os.path.join(d, fn), encoding='utf-8', errors='replace').read()))
    clash = [i for i in ids if i in others]
    assert not clash, clash


STRIP_FILE = os.path.join(MOD, 'common', 'scripted_effects', 'wif_ger_strip_spirits.txt')


def top_level_blocks(text):
    """Names of the blocks directly inside a { } body, comments stripped."""
    text = re.sub(r'#[^\n]*', '', text)
    names, depth, i = [], 0, 0
    for m in re.finditer(r'([A-Za-z0-9_\.]+)\s*=\s*\{|\{|\}', text):
        tok = m.group(0)
        if tok == '}':
            depth -= 1
        elif tok == '{':
            depth += 1
        else:
            if depth == 0:
                names.append(m.group(1))
            depth += 1
    return names


def block_body(text, start):
    """The text between the brace at text[start] and its partner."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    raise ValueError('unbalanced')


def german_spirits():
    """Every national spirit (the 'country' category) Germany can hold: the
    German idea files, vanilla's or the mod's override, and the mod's
    wif_ger_* files. Laws live in other categories and are left alone."""
    files = {}
    for root in (GAME, MOD):
        d = os.path.join(root, 'common', 'ideas')
        for fn in os.listdir(d):
            if fn == 'GER.txt' or fn.startswith('wif_ger_'):
                files[fn] = os.path.join(d, fn)      # the mod's copy wins
    ideas = set()
    for path in files.values():
        text = re.sub(r'#[^\n]*', '', open(path, encoding='utf-8-sig', errors='replace').read())
        for m in re.finditer(r'\bcountry\s*=\s*\{', text):
            ideas |= set(top_level_blocks(block_body(text, m.end() - 1)))
    mods = set()
    for root in (GAME, MOD):
        d = os.path.join(root, 'common', 'dynamic_modifiers')
        for fn in os.listdir(d):
            text = re.sub(r'#[^\n]*', '', open(os.path.join(d, fn), encoding='utf-8-sig', errors='replace').read())
            mods |= {n for n in top_level_blocks(text) if n.startswith(('GER_', 'wif_ger_'))}
    return sorted(ideas), sorted(mods)


def write_strip():
    ideas, mods = german_spirits()
    out = ['# GENERATED by tools/gen_ger_road_to_civil_war.py - do not edit by hand.',
           '#',
           '# Collapse of the Reich (events/wif_ger_collapse.txt): Bormann\'s German Reich',
           '# is the technical successor, but keeps none of the old Reich\'s national',
           '# spirits. Every German spirit and dynamic modifier the game and the mod',
           '# define, read from the idea and dynamic modifier files. German scope.',
           '', 'wif_ger_strip_spirits = {']
    for i in ideas:
        out.append(f'\tif = {{ limit = {{ has_idea = {i} }} remove_ideas = {i} }}')
    for d in mods:
        out.append(f'\tif = {{ limit = {{ has_dynamic_modifier = {{ modifier = {d} }} }} remove_dynamic_modifier = {{ modifier = {d} }} }}')
    out.append('}')
    open(STRIP_FILE, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    return len(ideas), len(mods)


