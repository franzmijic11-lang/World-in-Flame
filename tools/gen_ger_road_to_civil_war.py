def prereq_trigger(f):
    out = []
    if f.any_ and len(f.pre) > 1:
        out.append('OR = {\n' + ''.join(f'\thas_completed_focus = {p}\n' for p in f.pre) + '}')
    else:
        out += [f'has_completed_focus = {p}' for p in f.pre]
