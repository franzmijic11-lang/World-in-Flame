"""Germany's road from Totaler Sieg to the civil war - the middle of the
wif_ger_victory_focus tree (common/national_focus/wif_ger_victory.txt).

Planned in the Focus Tree Planner (map "Speer's Economy (draft)"). Planner x
plus 68 is the game's x; y is the same.

Writes:
  * the focuses, spliced between the GENERATED markers in wif_ger_victory.txt
  * common/scripted_effects/wif_ger_road_auto.txt - one try-to-start effect per
    focus that completes itself, and wif_ger_road_try_all, which runs them all
  * events/wif_ger_road_auto.txt - the hidden events that complete those focuses
  * localisation/english/wif_ger_road_focus_l_english.yml - names, descriptions
    and every tooltip key the focuses use

A focus that completes itself works the way Himmler's do
(events/wif_ger_himmler_schemes.txt): it shines, a timed flag drives the
progress tooltip, and a hidden event completes it - in the name of the Inner
Circle member doing it, or of nobody when it simply happens to Germany. Start
conditions are re-checked by wif_ger_road_try_all, which every focus here
calls when it completes and on_monthly_GER calls once a month.

The mechanics these rewards call (distrust, the succession contest, the
decisions, ideas and events) are hand-written in wif_ger_road.txt files.

Run from anywhere: python tools/gen_ger_road_to_civil_war.py
"""
