def define_before_use(text):
    """Order top-level scripted effects so each is defined before any caller.

    Blocks are cut at every column-0 `name = {`, carrying the comment lines
    directly above them along; the file header stays first.
    """
    import re
    nl = chr(10)
    lines = text.split(nl)
    starts = [i for i, l in enumerate(lines) if re.match(r"^[a-z_0-9]+ = \{", l)]
    cut = []
    for i in starts:
        j = i
        while j > 0 and lines[j - 1].startswith("#"):
            j -= 1
        cut.append(j)
    head = nl.join(lines[:cut[0]])
    blocks = {}
    order = []
    for n, j in enumerate(cut):
        end = cut[n + 1] if n + 1 < len(cut) else len(lines)
        name = lines[starts[n]].split(" ")[0]
        blocks[name] = nl.join(lines[j:end]).rstrip(nl)
        order.append(name)
    done, out = set(), []

    def visit(name):
        if name in done:
            return
        done.add(name)
        for dep in re.findall(r"\b(wif_cg_[a-z_0-9]+) = yes", blocks[name]):
            if dep in blocks:
                visit(dep)
        out.append(blocks[name])

    for name in order:
        visit(name)
    return head.rstrip(nl) + nl * 2 + (nl * 2).join(out) + nl



