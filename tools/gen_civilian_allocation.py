"""Generate the civilian factory allocation system.

Writes five files from one description of the seven compartments, because the
window and the click effects repeat the same block seven times and hand-copied
repetition is where typos hide:

    common/scripted_effects/wif_civilian_allocation.txt
    common/dynamic_modifiers/wif_civilian_allocation.txt
    common/scripted_guis/wif_civilian_allocation_gui.txt
    interface/wif_civilian_allocation.gui
    localisation/english/wif_civilian_allocation_l_english.yml

Edit THIS file and re-run it (python tools/gen_civilian_allocation.py from the
mod root); do not hand-edit the outputs, the next run overwrites them.

Encoding follows the mod's rule: .yml gets a UTF-8 BOM, .txt/.gui must not.
Line endings are CRLF to match the rest of the mod.
"""

