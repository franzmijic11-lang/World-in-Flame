def load():
    m = json.load(open(p('tools', SNAPSHOT), encoding='utf-8'))
    by_id = {f['id']: f for f in m['focuses']}
    for f in m['focuses']:
        f['key'] = f['fid'][len(P):]
        assert f['key'] in R, f'no reward for {f["fid"]}'
    assert not set(R) - {f['key'] for f in m['focuses']}, set(R) - {f['key'] for f in m['focuses']}
    return m, by_id


def gen_tree(m, by_id):
    maxy = max(f['y'] for f in m['focuses'])
    o = [HEADER.rstrip('\n'), f'# Layout from the Focus Tree Planner (tools/{SNAPSHOT}). Loaded by wif_osb_satellite.', '',
         'focus_tree = {', f'\tid = {TREE}', '', '\tcountry = {', '\t\tfactor = 0', '\t}', '',
         '\tdefault = no', '\treset_on_civilwar = no',
         '\t# below the lowest focus: the 770x380 continuous window covers the top-left otherwise',
         f'\tcontinuous_focus_position = {{ x = 50 y = {(maxy + 2) * 130} }}', '']
    for f in sorted(m['focuses'], key=lambda f: (f['y'], f['x'])):
        k = f['key']
        o += ['\tfocus = {', f'\t\tid = {f["fid"]}', f'\t\ticon = {ICON.get(k, ICON_BRANCH[f["branch"]])}']
        if f['pre']:
            ids = [by_id[i]['fid'] for i in f['pre']]
            if f['any']:
                o.append('\t\tprerequisite = { ' + ' '.join(f'focus = {i}' for i in ids) + ' }')
            else:
                o += [f'\t\tprerequisite = {{ focus = {i} }}' for i in ids]
        if f['mx']:
            o.append('\t\tmutually_exclusive = { ' + ' '.join(f'focus = {by_id[i]["fid"]}' for i in f['mx']) + ' }')
        o += [f'\t\tx = {f["x"]}', f'\t\ty = {f["y"]}', f'\t\tcost = {cost(f["days"])}']
        if k in AVAILABLE:
            o += ['\t\tavailable = {', indent(AVAILABLE[k], 3), '\t\t}']
        o.append(f'\t\tai_will_do = {{ factor = {AI.get(k, 10)} }}')
        o.append(f'\t\tsearch_filters = {{ {FILTER[f["branch"]]} }}')
        o += ['\t\tcompletion_reward = {', indent(R[k], 3), '\t\t}', '\t}', '']
    o += ['}', '']
    write(f'common/national_focus/{TREE}.txt', '\n'.join(o))


