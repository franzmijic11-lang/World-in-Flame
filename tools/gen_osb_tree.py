def patch_ceiling():
    for rel in ('common/scripted_effects/wif_factory_balance.txt', 'common/ai_strategy/wif_factory_balance.txt'):
        path = p(*rel.split('/'))
        raw = open(path, 'rb').read()
        bom = raw.startswith(b'\xef\xbb\xbf')
        s = raw.decode('utf-8-sig')
        n = len(re.findall(r'(?<!#)\bwif_is_soviet_successor = yes', s))
        s = re.sub(r'(?m)^([^#\n]*?)\bwif_is_soviet_successor = yes', r'\1wif_ceiling_exempt = yes', s)
        open(path, 'wb').write((b'\xef\xbb\xbf' if bom else b'') + s.encode('utf-8'))
        print(f'ceiling: {n} checks now use wif_ceiling_exempt in {rel}')


def splice_satellite():
    path = p('common', 'scripted_effects', 'wif_ger_himmler.txt')
    raw = open(path, 'rb').read()
    s = raw.decode('utf-8')
    nl = '\r\n' if '\r\n' in s else '\n'
    if TREE in s:
        print('satellite already loads the tree')
        return
    old = '\t\twif_osb_setup = yes' + nl + '\t\tpuppet = OSB' + nl
    assert s.count(old) == 1, s.count(old)
    new = old + ('\t\t# the satellite\'s own tree (tools/gen_osb_tree.py)' + nl +
                 f'\t\tOSB = {{ load_focus_tree = {{ tree = {TREE} keep_completed = no }} }}' + nl)
    open(path, 'wb').write(s.replace(old, new).encode('utf-8'))
    print('wif_osb_satellite now loads the tree')


def gen_raids():
    src = open(os.path.join(GAME, 'common', 'raids', 'nuclear_raids.txt'), encoding='utf-8-sig').read()
    body_start = src.index('{', src.index('types')) + 1
    end = src.rindex('}')
    inner = src[body_start:end]
    blocks = []
    i = 0
    for m in re.finditer(r'^\t(\w+) = \{', inner, re.M):
        if m.start() < i:
            continue
        d, k = 1, m.end()
        while d:
            d += {'{': 1, '}': -1}.get(inner[k], 0)
            k += 1
        blocks.append((m.group(1), inner[m.start():k]))
        i = k
    out = []
    loc = []

    def add_ai(b):
        return re.sub(r'(ai_will_do = \{\n\t\t\tbase = [\d.]+\n)',
                      r'\1\t\t\tmodifier = {\n\t\t\t\tfactor = 5 # WiF: the Ordensstaat\'s First Strike Doctrine\n\t\t\t\thas_country_flag = wif_osb_first_strike\n\t\t\t}\n', b, count=1)

    for name, b in blocks:
        assert re.search(r'\n\t\tvisible = \{', b), name
        # the vanilla type: hidden from a country with Cheap Fire
        v = re.sub(r'\n\t\tvisible = \{', '\n\t\tvisible = {\n\t\t\tNOT = { has_country_flag = wif_osb_cheap_fire } # WiF', b, count=1)
        out.append(add_ai(v))
        # the _osb copy: a quarter of the command power, a lower AI threshold
        c = b.replace(f'\t{name} = {{', f'\t{name}_osb = {{', 1)
        c = re.sub(r'command_power = (\d+)', lambda m: f'command_power = {max(1, int(m.group(1)) // 4)}', c, count=1)
        if 'ai_min_success_chance' in c:
            c = re.sub(r'ai_min_success_chance = [\d.]+', 'ai_min_success_chance = 0.30', c, count=1)
        else:
            c = c.replace(f'\t{name}_osb = {{', f'\t{name}_osb = {{\n\t\tai_min_success_chance = 0.30', 1)
        c = re.sub(r'\n\t\tvisible = \{', '\n\t\tvisible = {\n\t\t\thas_country_flag = wif_osb_cheap_fire # WiF', c, count=1)
        out.append(add_ai(c))
        loc += [f' raid_type_{name}_osb:0 "${{raid_type_{name}}}$"'.replace('${', '$').replace('}$', '$'),
                f' raid_type_{name}_osb_desc:0 "$raid_type_{name}_desc$"']
    text = ('# Welt in Flammen: a copy of vanilla common/raids/nuclear_raids.txt, written by\n'
            '# tools/gen_osb_tree.py - RE-RUN after a game update. Each vanilla nuclear raid\n'
            '# is hidden from a country with wif_osb_cheap_fire (the Ordensstaat\'s Cheap\n'
            '# Fire), which gets an _osb copy at a quarter of the command power instead.\n'
            '# wif_osb_first_strike multiplies every nuclear raid\'s AI weight by 5.\n\n'
            + src[:body_start] + '\n' + '\n\n'.join(out) + '\n' + src[end:])
    write('common/raids/nuclear_raids.txt', text, crlf=False)
    return loc


def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


def fix(s):
    for a, b in TEXT_FIX:
        s = s.replace(a, b)
    return s


def gen_loc(m, raid_loc):
    o = ['l_english:']
    for f in m['focuses']:
        flav = re.split(r'\n\n(?:Effect:|Requires|Available)', f['desc'])[0].strip()
        o += [f' {f["fid"]}:0 "{esc(fix(f["name"]))}"', f' {f["fid"]}_desc:0 "{esc(fix(flav))}"']
    for k, (_, _, name, desc) in IDEAS.items():
        o += [f' {k}:0 "{esc(name)}"', f' {k}_desc:0 "{esc(desc)}"']
    for k, (_, name, _) in OPINION.items():
        o.append(f' {k}:0 "{esc(name)}"')
    o += [f' {k}:0 "{v}"' for k, v in TOOLTIPS.items()]
    o += raid_loc
    write('localisation/english/wif_osb_l_english.yml', '\n'.join(o) + '\n', bom=True, crlf=False)


