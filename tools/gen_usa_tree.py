"""The United States 1936-1952 (wif_usa_focus): the WiF American tree.

Source of truth for everything main() writes:

    python tools/gen_usa_tree.py

Run tools/gen_usa_elections.py too - the tree uses its Congress triggers
(wif_ue_congress_majority / _supermajority / wif_ue_senate_treaty) and its
region shifts (wif_ue_shift_<region>, temp wif_ue_party / wif_ue_amt).

Layout, names, durations and prerequisites: Focus Tree Planner map `usa-wif`,
snapshotted in tools/planner_usa.json. Rewards live in R, keyed by fid minus
wif_usa_. The planner descriptions are design notes; only their flavour text
(before "Effect:") reaches the game, the tooltips show the real effects.

1936-45 is the historical path: the New Deal and THE DEPRESSION, industry,
Science Haven (+1 research slot at OSRD), neutrality, the armed forces. In
1945 The World After the War opens one of four branches; only Beaten but not
Defeated (the US accepted Germany's peace AND Japan drove it out of Asia) has
content, 1945-1952. The other three are placeholders (available = never)
until the German and Japanese defeat mechanics exist.

THE DEPRESSION: country variable wif_usa_dep, 0-100, starts at 80 (45 in the
1939 start). A dynamic modifier scales with it: up to -15% stability, -20%
factory output, +15% consumer goods, -10% construction speed. It replaces
vanilla's great_depression ideas at game start.
"""
