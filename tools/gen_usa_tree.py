def in_state(s, body, fallback=True):
    o = j('if = {', f'\tlimit = {{ {s} = {{ is_owned_by = ROOT }} }}', f'\t{s} = {{', indent(body, 2), '\t}', '}')
    if fallback:
        o = j(o, 'else = {', '\trandom_owned_controlled_state = {', '\t\tlimit = { is_core_of = ROOT }',
              '\t\tprioritize = { ' + str(s) + ' }', indent(body, 2), '\t}', '}')
    return o


