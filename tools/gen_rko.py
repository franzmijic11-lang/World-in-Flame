def cover(img, w, h, top_bias=0.25):
    img = img.convert('RGBA')
    sw, sh = img.size
    if sw / sh > w / h:
        nw = int(sh * w / h)
        x = (sw - nw) // 2
        img = img.crop((x, 0, x + nw, sh))
    else:
        nh = int(sw * h / w)
        y = int((sh - nh) * top_bias)
        img = img.crop((0, y, sw, y + nh))
    return img.resize((w, h), Image.LANCZOS)


