def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


def flavour(desc):
    keep = []
    for para in desc.split('\n\n'):
        if re.match(r"^(Effect:|Available:|AI:|AFTER |[A-Z][A-Z' ]{3,}[A-Z](?: \(|:| -))", para):
            if keep:
                break
            continue
        keep.append(para.strip())
    return '\n\n'.join(keep)


def gen_loc(m):
    L = rkm_loc()
    for a, new in (('wif_attack_partisan_activity', 'wif_rko_attack_partisan_activity'), ('wif_deploy_mechanised_forces', 'wif_rko_deploy_mechanised_forces'),
                   ('wif_paulus_gambit', 'wif_rko_police_offensive')):
        TT[new] = belarusify(L[a])
        TT[new + '_desc'] = belarusify(L[a + '_desc'])
    o = ['l_english:']
    for f in m['focuses']:
        o += [f' {f["fid"]}:0 "{esc(f["name"])}"', f' {f["fid"]}_desc:0 "{esc(flavour(f["desc"]))}"']
    for k, (_, _, name, desc) in IDEAS.items():
        o += [f' {k}:0 "{esc(name)}"', f' {k}_desc:0 "{esc(desc)}"']
    for k, (_, name) in OPINION.items():
        o.append(f' {k}:0 "{esc(name)}"')
    for k, v in TT.items():
        o.append(f' {k}:0 "{esc(v)}"')
    keys = [l.split(':')[0].strip() for l in o[1:]]
    dup = {k for k in keys if keys.count(k) > 1}
    assert not dup, f'duplicate loc keys {dup}'
    write('localisation/english/wif_rko_l_english.yml', '\n'.join(o) + '\n', bom=True, crlf=False)


