# ------------------------------------------------------------------ tech
def tech_graph():
    files = {}
    for root in (os.path.join(GAME, 'common', 'technologies'), os.path.join(UTTNH, 'common', 'technologies'),
                 os.path.join(MOD, 'common', 'technologies')):
        for f in glob.glob(os.path.join(root, '*.txt')):
            files[os.path.basename(f)] = f
    children = {}
    for f in files.values():
        t = re.sub(r'#[^\n]*', '', open(f, encoding='utf-8-sig', errors='ignore').read())
        m = re.search(r'technologies\s*=\s*\{', t)
        if not m:
            continue
        i = m.end()
        ent = re.compile(r'\s*([A-Za-z0-9_@.]+)\s*=\s*')
        while i < len(t):
            mm = ent.match(t, i)
            if not mm:
                if t[i:].lstrip().startswith('}'):
                    break
                i += 1
                continue
            k = mm.end()
            if k < len(t) and t[k] == '{':
                name, k, d = mm.group(1), k + 1, 1
                start = k
                while d and k < len(t):
                    d += {'{': 1, '}': -1}.get(t[k], 0)
                    k += 1
                body = t[start:k]
                if not name.startswith('@') and 'research_cost' in body:
                    children[name] = sorted(set(re.findall(r'leads_to_tech\s*=\s*([A-Za-z0-9_]+)', body)))
                i = k
            else:
                tok = re.compile(r'\S+').match(t, k)
                i = tok.end() if tok else k + 1
    return children


def tech_effect():
    ch = tech_graph()
    o = [HEADER + '# Partisan scope, global event_target:wif_rko_donor = RKO.\n\n'
         '# Every technology Ostland has (the Council of Brothers, the Estonian Liberation Front).\nwif_rko_inherit_tech_full = {']
    for t in sorted(ch):
        o.append(f'\tif = {{ limit = {{ event_target:wif_rko_donor = {{ has_tech = {t} }} }} set_technology = {{ {t} = 1 popup = no }} }}')
    o.append('}\n\n# Ostland\'s tech minus one step on every line (Belarus).\nwif_rko_inherit_tech_minus = {')
    n = 0
    for t, kids in sorted(ch.items()):
        kids = [k for k in kids if k in ch]
        if not kids:
            continue
        fam = re.sub(r'[_\d]+$', '', t)
        same = [k for k in kids if k.startswith(fam)]
        if same:
            kids = same
        n += 1
        o.append(f'\tif = {{ limit = {{ event_target:wif_rko_donor = {{ has_tech = {t} OR = {{ {" ".join(f"has_tech = {k}" for k in kids)} }} }} }} set_technology = {{ {t} = 1 popup = no }} }}')
    o.append('}')
    assert 'rangers_tech3' in ch, 'UTTNH rangers techs not found'
    write('common/scripted_effects/wif_rko_tech_auto.txt', '\n'.join(o) + '\n')
    print(len(ch), 'techs,', n, 'minus-one lines')


