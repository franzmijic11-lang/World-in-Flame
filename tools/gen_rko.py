def rkm_loc():
    d = {}
    for l in open(p('localisation', 'english', 'wif_rkm_l_english.yml'), encoding='utf-8-sig'):
        m = re.match(r'\s+([\w.]+):\d*\s*"(.*)"\s*$', l)
        if m:
            d[m.group(1)] = m.group(2)
    return d


def belarusify(s):
    for a, b in [('Russian', 'Belarusian'), ('Moskowien', 'the Reichskommissariat'), ('Moskau', 'Minsk'), ("Paulus's Gambit", 'Police Offensive'),
                 ("Under General Paulus's doctrine", 'Under the Higher SS and Police Leader'), ('SS mechanised forces', 'mechanised police forces')]:
        s = s.replace(a, b)
    return s


