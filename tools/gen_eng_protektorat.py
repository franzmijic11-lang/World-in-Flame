def write(rel, text, bom=False, crlf=True):
    path = p(rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if crlf:
        text = text.replace('\r\n', '\n').replace('\n', '\r\n')
    with open(path, 'w', encoding='utf-8-sig' if bom else 'utf-8', newline='') as f:
        f.write(text)
    print('wrote', rel)


def top_level_blocks(text):
    names, depth = [], 0
    for m in re.finditer(r'([A-Za-z0-9_\.]+)\s*=\s*\{|\{|\}', text):
        tok = m.group(0)
        if tok == '}':
            depth -= 1
        elif tok == '{':
            depth += 1
        else:
            if depth == 0:
                names.append(m.group(1))
            depth += 1
    return names


def block_body(text, start):
    depth = 0
    for i in range(start, len(text)):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    raise ValueError('unbalanced')


def british_spirits():
    files = {}
    for root in (GAME, MOD):
        d = os.path.join(root, 'common', 'ideas')
        for fn in os.listdir(d):
            if fn.endswith('.txt'):
                files[fn] = os.path.join(d, fn)          # the mod's copy wins
    ideas = set()
    for fn, path in files.items():
        text = re.sub(r'#[^\n]*', '', open(path, encoding='utf-8-sig', errors='replace').read())
        for m in re.finditer(r'\bcountry\s*=\s*\{', text):
            names = top_level_blocks(block_body(text, m.end() - 1))
            if fn == 'britain.txt':
                ideas |= set(names)
            else:
                ideas |= {n for n in names if n.startswith('ENG_')}
    ideas = {i for i in ideas if not i.startswith('wif_')}
    mods = set()
    for root in (GAME, MOD):
        d = os.path.join(root, 'common', 'dynamic_modifiers')
        for fn in os.listdir(d):
            text = re.sub(r'#[^\n]*', '', open(os.path.join(d, fn), encoding='utf-8-sig', errors='replace').read())
            mods |= {n for n in top_level_blocks(text) if n.startswith('ENG_')}
    return sorted(ideas), sorted(mods)


