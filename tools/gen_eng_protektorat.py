def splice_peace():
    path = p('common', 'scripted_effects', 'wif_peace_deal.txt')
    raw = open(path, 'rb').read()
    s = raw.decode('utf-8')
    nl = '\r\n' if '\r\n' in s else '\n'
    call = '\t\t\twif_eng_become_protektorat = yes\t# tools/gen_eng_protektorat.py'
    if 'wif_eng_become_protektorat' in s:
        print('peace deal already calls it')
        return
    anchor = '\t\t\tpromote_character = ENG_oswald_mosley' + nl
    assert s.count(anchor) == 1, s.count(anchor)
    s = s.replace(anchor, anchor + call + nl)
    open(path, 'wb').write(s.encode('utf-8'))
    print('spliced the call into wif_peace_deal.txt')


def cover(img, w, h, top_bias=0.0):
    from PIL import Image
    img = img.convert('RGB')
    sw, sh = img.size
    if sw / sh > w / h:
        nw = int(sh * w / h); x = (sw - nw) // 2; img = img.crop((x, 0, x + nw, sh))
    else:
        nh = int(sw * h / w); y = int((sh - nh) * top_bias); img = img.crop((0, y, sw, y + nh))
    return img.resize((w, h), Image.LANCZOS)


