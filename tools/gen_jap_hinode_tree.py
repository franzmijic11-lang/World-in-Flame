def ors(ids):
    return ' '.join(f'state = {s}' for s in ids)


# ------------------------------------------------------------------ effect helpers
def pp(n): return f'add_political_power = {n}'
def stab(n): return f'add_stability = {n}'
def ws(n): return f'add_war_support = {n}'
def idea(k): return f'add_ideas = {k}'
def nukes(n): return f'add_nuclear_bombs = {n}'
def slot(n=1): return f'add_research_slot = {n}'
def flag(f): return f'set_country_flag = {f}'
def tt(key, body): return j(f'custom_effect_tooltip = {key}', 'hidden_effect = {', indent(body, 1), '}')


def bonus(name, cats, b=0.5, uses=1):
    return j('add_tech_bonus = {', f'\tname = {name}', f'\tbonus = {b}', f'\tuses = {uses}',
             *[f'\tcategory = {c}' for c in cats], '}')


def subject(tag, body):
    return j('if = {', f'\tlimit = {{ {tag} = {{ exists = yes is_subject_of = ROOT }} }}',
             f'\t{tag} = {{', indent(body, 2), '\t}', '}')


def every_subject(body):
    return j('every_country = {', '\tlimit = { is_subject_of = ROOT }', indent(body, 1), '}')


def opinion_of_us(mod):
    return f'add_opinion_modifier = {{ target = ROOT modifier = {mod} }}'


def autonomy(n):
    return f'add_autonomy_ratio = {{ value = {n} localization = wif_hin_autonomy_loc }}'


def core(states, key):
    body = j('every_owned_state = {', f'\tlimit = {{ OR = {{ {ors(states)} }} }}', '\tadd_core_of = ROOT', '}')
    return tt(key, body)


def in_state(s, body):
    return j('if = {', f'\tlimit = {{ {s} = {{ is_owned_by = ROOT }} }}', f'\t{s} = {{', indent(body, 2), '\t}', '}')


def building(kind, n=1, slots=True):
    return j('add_extra_state_shared_building_slots = %d' % n if slots else '',
             f'add_building_construction = {{ type = {kind} level = {n} instant_build = yes }}')


def province_building(kind, n=1):
    return (f'add_building_construction = {{ type = {kind} level = {n} instant_build = yes '
            'province = { all_provinces = yes limit_to_naval_base = yes } }')


def rights(tag, resources, key):
    body = j(f'{tag} = {{', '\tevery_owned_state = {',
             f'\t\tOWNER = {{ give_resource_rights = {{ receiver = ROOT state = PREV resources = {{ {" ".join(resources)} }} }} }}',
             '\t}', '}')
    return tt(key, j('if = {', f'\tlimit = {{ {tag} = {{ exists = yes is_subject_of = ROOT }} }}', indent(body, 1), '}'))


def home_factories(kind, n):
    one = j('random_owned_controlled_state = {',
            '\tlimit = { is_core_of = ROOT NOT = { ' + ors(KOREA) + ' ' + ors(TAIWAN) + ' } }',
            '\tprioritize = { 1018 1019 1020 }',
            indent(building(kind), 1), '}')
    return '\n'.join([one] * n)


def lose_factories(tag, n):
    one = j('random_owned_state = {', '\tlimit = { industrial_complex > 0 }',
            '\tremove_building = { type = industrial_complex level = 1 }', '}')
    return subject(tag, '\n'.join([one] * n))


