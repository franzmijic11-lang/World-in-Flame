def load():
    m = json.load(open(p('tools', SNAPSHOT), encoding='utf-8'))
    m = m.get('data', m)
    by_id = {f['id']: f for f in m['focuses']}
    keys = {f['fid'][len(P):] for f in m['focuses']}
    for f in m['focuses']:
        f['key'] = f['fid'][len(P):]
    missing = sorted(k for k in keys if k not in R or k not in ICON)
    assert not missing, f'no reward/icon for {missing}'
    extra = sorted(set(R) - keys)
    if extra:
        print('NOTE: rewards for focuses no longer in the planner (ignored):', extra)
    return m, by_id


def check_icons():
    names, pics = set(), set()
    for root in (GAME, MOD):
        for fn in __import__('glob').glob(os.path.join(root, 'interface', '*.gfx')):
            t = open(fn, encoding='utf-8', errors='ignore').read()
            names |= set(re.findall(r'name\s*=\s*"?(GFX_[A-Za-z0-9_]+)', t))
    pics = {n[len('GFX_idea_'):] for n in names if n.startswith('GFX_idea_')}
    bad = sorted({v for v in ICON.values() if v not in names})
    assert not bad, f'missing icons: {bad}'
    badp = sorted({v[0] for v in list(IDEAS.values()) + list(SPIRITS.values()) if v[0] not in pics})
    assert not badp, f'missing idea pictures: {badp}'


def check_layout(m, by_id):
    pos = {(f['x'], f['y']): f for f in m['focuses']}
    probs = []
    for f in m['focuses']:
        for g in m['focuses']:
            if f is not g and f['y'] == g['y'] and abs(f['x'] - g['x']) < 2:
                probs.append(f'{f["fid"]} and {g["fid"]} share row {f["y"]} one column apart')
        for i in f['pre']:
            par = by_id[i]
            if par['y'] >= f['y']:
                probs.append(f'{f["fid"]} is not below its parent {par["fid"]}')
            for y in range(par['y'] + 1, f['y']):
                if (f['x'], y) in pos:
                    probs.append(f'line {par["fid"]} -> {f["fid"]} runs through {pos[(f["x"], y)]["fid"]}')
    return sorted(set(probs))


def gen_tree(m, by_id):
    maxy = max(f['y'] for f in m['focuses'])
    o = [HEADER.rstrip('\n'), f'# Layout from the Focus Tree Planner (tools/{SNAPSHOT}). Loaded by Pax Romana',
         f'# ({PAX}, common/national_focus/wif_ita_pax_romana_shared.txt).', '',
         'focus_tree = {', f'\tid = {TREE}', '', '\tcountry = {', '\t\tfactor = 0', '\t}', '',
         '\tdefault = no', '\treset_on_civilwar = no',
         f'\tcontinuous_focus_position = {{ x = 50 y = {(maxy + 2) * 130} }}', '']
    for f in sorted(m['focuses'], key=lambda f: (f['y'], f['x'])):
        k = f['key']
        o += ['\tfocus = {', f'\t\tid = {f["fid"]}', f'\t\ticon = {ICON[k]}']
        if f['pre']:
            ids = [by_id[i]['fid'] for i in f['pre']]
            if f['any']:
                o.append('\t\tprerequisite = { ' + ' '.join(f'focus = {i}' for i in ids) + ' }')
            else:
                o += [f'\t\tprerequisite = {{ focus = {i} }}' for i in ids]
        if f['mx']:
            o.append('\t\tmutually_exclusive = { ' + ' '.join(f'focus = {by_id[i]["fid"]}' for i in f['mx']) + ' }')
        o += [f'\t\tx = {f["x"]}', f'\t\ty = {f["y"]}', f'\t\tcost = {cost(f["days"])}']
        if k in AVAILABLE:
            o += ['\t\tavailable = {', indent(AVAILABLE[k], 3), '\t\t}']
        if k in BYPASS:
            o += ['\t\tbypass = {', indent(BYPASS[k], 3), '\t\t}']
        o.append(f'\t\tai_will_do = {{ factor = {AI.get(k, 10)} }}')
        o.append(f'\t\tsearch_filters = {{ {FILTER[f["branch"]]} }}')
        o += ['\t\tcompletion_reward = {', indent(R[k], 3), '\t\t}', '\t}', '']
    o += ['}', '']
    write(f'common/national_focus/{TREE}.txt', '\n'.join(o))


