def gen_loc(m):
    v = json.load(open(p('tools', 'planner_ita_vanilla_pax.json'), encoding='utf-8'))
    pax = [f for f in v['focuses'] if f['fid'] == PAX][0]
    o = ['l_english:']
    for f in m['focuses'] + [pax]:
        flav = re.split(r'\n\n(?:Effect:|Requires|Available|Prerequisite|Bypassed|This tree replaces|PEACE DEAL|STARTING SPIRITS|The ONLY|The only|But:)', f['desc'])[0].strip()
        o += [f' {f["fid"]}:0 "{esc(f["name"])}"', f' {f["fid"]}_desc:0 "{esc(flav)}"']
    for s, (_, tiers, name, desc, suf) in SPIRITS.items():
        for t in range(1, len(tiers) + 1):
            o += [f' wif_ita_{s}_{t}:0 "{esc(name + suf[t - 1])}"', f' wif_ita_{s}_{t}_desc:0 "{esc(desc)}"']
    for k, (_, _, name, desc) in IDEAS.items():
        o += [f' {k}:0 "{esc(name)}"', f' {k}_desc:0 "{esc(desc)}"']
    for k, (_, name) in OPINION.items():
        o.append(f' {k}:0 "{esc(name)}"')
    for k, v2 in TT.items():
        o.append(f' {k}:0 "{esc(v2)}"')
    for k, v2 in TRIG.items():
        o.append(f' wif_ita_{k}_trigger_tt:0 "{esc(v2)}"')
    o += [' wif_ita_autonomy_loc:0 "Pax Romana"',
          ' wif_ita_roman_pact:0 "The Roman Pact"',
          ' wif_ita_latin_research_name:0 "Latin Research Cooperation"',
          ' wif_ita_latin_research_desc:0 "Italian and Spanish scientists, sharing their work."']
    for name in sorted({n for r in R.values() for n in re.findall(r'name = (\w+)_bonus', r)}):
        o.append(f' {name}_bonus:0 "Pax Romana"')
    keys = [l.split(':')[0].strip() for l in o[1:]]
    dup = {k for k in keys if keys.count(k) > 1}
    assert not dup, f'duplicate loc keys: {dup}'
    write('localisation/english/wif_ita_pax_romana_l_english.yml', '\n'.join(o) + '\n', bom=True, crlf=False)


