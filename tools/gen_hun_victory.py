def icon_names():
    names = set()
    for root in (GAME, MOD, UTTNH):
        for fn in glob.glob(os.path.join(root, 'interface', '*.gfx')):
            names |= set(re.findall(r'name\s*=\s*"?(GFX_[A-Za-z0-9_]+)', open(fn, encoding='utf-8', errors='ignore').read()))
    return names


def gen_tree(names):
    m = json.load(open(p('tools', 'planner_hunv.json'), encoding='utf-8'))
    m = m.get('data', m)
    by_id = {f['id']: f for f in m['focuses']}
    keys = [f['fid'][len(P):] for f in m['focuses']]
    assert all(f['fid'].startswith(P) for f in m['focuses']), [f['name'] for f in m['focuses'] if not f['fid'].startswith(P)]
    for d, what in ((R, 'reward'), (ICON, 'icon')):
        miss = sorted(k for k in keys if k not in d)
        assert not miss, f'no {what} for {miss}'
    bad = sorted(ICON[k] for k in keys if ICON[k] not in names)
    assert not bad, f'missing icons {bad}'
    maxy = max(f['y'] for f in m['focuses'])
    o = [HEADER.rstrip('\n'), '# Layout from the Focus Tree Planner (tools/planner_hunv.json). Loaded by Victorious in a New World.', '',
         'focus_tree = {', '\tid = wif_hun_victory_focus', '', '\tcountry = {\n\t\tfactor = 0\n\t}', '',
         '\tdefault = no', '\treset_on_civilwar = no', f'\tcontinuous_focus_position = {{ x = 50 y = {(maxy + 2) * 130} }}', '']
    for f in sorted(m['focuses'], key=lambda f: (f['y'], f['x'])):
        fid = f['fid']
        k = fid[len(P):]
        o += ['\tfocus = {', f'\t\tid = {fid}', f'\t\ticon = {ICON[k]}']
        if f['pre']:
            ids = [by_id[i]['fid'] for i in f['pre']]
            if f.get('any'):
                o.append('\t\tprerequisite = { ' + ' '.join(f'focus = {i}' for i in ids) + ' }')
            else:
                o += [f'\t\tprerequisite = {{ focus = {i} }}' for i in ids]
        if f['mx']:
            o.append('\t\tmutually_exclusive = { ' + ' '.join(f'focus = {by_id[i]["fid"]}' for i in f['mx']) + ' }')
        o += [f'\t\tx = {f["x"]}', f'\t\ty = {f["y"]}', f'\t\tcost = {cost(f["days"])}']
        if k == 'victorious':
            o.append('\t\tavailable = { always = no }')
        elif k in AVAILABLE:
            o.append(f'\t\tavailable = {{ {AVAILABLE[k]} }}')
        o.append(f'\t\tai_will_do = {{ {AI.get(k, "base = 10")} }}')
        o.append(f'\t\tsearch_filters = {{ {FILTER.get(f["branch"], "FOCUS_FILTER_POLITICAL")} }}')
        o += ['\t\tcompletion_reward = {', indent(R[k], 3), '\t\t}', '\t}', '']
    o += ['}', '']
    write('common/national_focus/wif_hun_victory_focus.txt', '\n'.join(o))
    return m


