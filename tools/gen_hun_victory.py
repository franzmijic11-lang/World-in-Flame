def patch_reunify():
    path = p('common', 'scripted_effects', 'zz_wif_ger_reunify.txt')
    raw = open(path, 'rb').read().decode('utf-8')
    if 'wif_cw_winner_' in raw:
        return
    nl = '\r\n' if '\r\n' in raw else '\n'
    a = '\t\tset_global_flag = wif_ger_civil_war_won' + nl
    assert raw.count(a) == 1
    add = (a + '\t\t# WiF Hungary (tools/gen_hun_victory.py): who won.' + nl +
           ''.join(f'\t\tif = {{ limit = {{ tag = {s} }} set_global_flag = wif_cw_winner_{s.lower()} }}' + nl for s in ALL_SIDES))
    raw = raw.replace(a, add)
    open(path, 'wb').write(raw.encode('utf-8'))
    print('patched zz_wif_ger_reunify.txt')


