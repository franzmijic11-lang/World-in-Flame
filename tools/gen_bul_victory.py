def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


def flavour(desc):
    keep = []
    for para in desc.split('\n\n'):
        if re.match(r"^(Effect|Available|Completes|AI|THE |BRANCHES|[A-Z][A-Z' ]{3,}[A-Z](?: \(|:| -))", para):
            if keep:
                break
            continue
        keep.append(para.strip())
    return '\n\n'.join(keep)


def gen_loc(m):
    o = ['l_english:']
    for f in m['focuses']:
        o += [f' {f["fid"]}:0 "{esc(f["name"])}"', f' {f["fid"]}_desc:0 "{esc(flavour(f["desc"]))}"']
    for k, (_, _, name, desc) in IDEAS.items():
        o += [f' {k}:0 "{esc(name)}"', f' {k}_desc:0 "{esc(desc)}"']
    for k, v in TT.items():
        o.append(f' {k}:0 "{esc(v)}"')
    for k in sorted(set(re.findall(r'name = (wif_bulv_tb_[a-z0-9_]+) bonus', ' '.join(R.values())))):
        o.append(f' {k}:0 "Bulgarian Focus"')
    keys = [l.split(':')[0].strip() for l in o[1:]]
    dup = {k for k in keys if keys.count(k) > 1}
    assert not dup, f'duplicate loc keys {dup}'
    write('localisation/english/wif_bulv_l_english.yml', '\n'.join(o) + '\n', bom=True, crlf=False)


