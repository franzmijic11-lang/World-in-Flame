def focus_span(t, fid):
    m = re.search(r'\n\tfocus = \{\s*\n\s*id = ' + fid + r'\b', t)
    assert m, fid
    i = m.start() + 1
    k, d = t.index('{', i) + 1, 1
    while d:
        d += {'{': 1, '}': -1}.get(t[k], 0)
        k += 1
    return i, k


def edit_focus(t, fid, fn):
    i, k = focus_span(t, fid)
    return t[:i] + fn(t[i:k]) + t[k:]


def sub1(pat, rep, s):
    s2, n = re.subn(pat, rep, s, count=1)
    assert n == 1, pat
    return s2


