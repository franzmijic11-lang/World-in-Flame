"""German tech icons, equipment art and 3D unit models for every German
Reichskommissariat and protectorate (user, 2026-11-24: RKU, RKO etc. showed
generic tech symbols).

Same method as tools/gen_warlord_soviet_art.py: HoI4 looks art up by tag first
(GFX_<TAG>_<name>, <TAG>_<name>_entity), so every GFX_GER_* sprite and
GER_*_entity from vanilla and UTTNH 3.0 gets a twin for each tag in RK_TAGS.
RE-RUN after updating UTTNH or adding an RK tag.

Writes:
  interface/zz_wif_rk_ger_sprites.gfx
  gfx/entities/zz_wif_rk_ger_units.asset
"""
import glob
import os
import re

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = r'C:\Program Files (x86)\Steam\steamapps\common\Hearts of Iron IV'
UTTNH = r'C:\Program Files (x86)\Steam\steamapps\workshop\content\394360\3413890094'
OUT_GFX = os.path.join(MOD, 'interface', 'zz_wif_rk_ger_sprites.gfx')
OUT_ASSET = os.path.join(MOD, 'gfx', 'entities', 'zz_wif_rk_ger_units.asset')
OLD = []


# Every German subject the Reich can set up: the Reichskommissariate, the
# Generalgouvernement and the two Bohemian protectorates (vanilla + WiF tags).
RK_TAGS = ['RKB', 'RKN', 'RKG', 'RKU', 'RKO', 'RKK', 'RKT', 'RKM', 'RKL', 'GEN', 'RKH', 'RKI', 'RKC', 'RGB', 'RKA',
           'RNA', 'RKV', 'RAN', 'RCO', 'RUS', 'RHD', 'RAR', 'ROA', 'RAA', 'RKF', 'RKR', 'RKZ', 'BMP', 'RKS',
           'OSB']   # the Ordensstaat Burgund too (user, 2026-11-27)


def warlord_tags():
    return RK_TAGS


def blocks(text, keyword):
    """Yield every balanced `keyword = { ... }` block (case-insensitive)."""
    text = re.sub(r'#[^\n]*', '', text)
    for m in re.finditer(r'\b' + keyword + r'\s*=\s*\{', text, re.I):
        i, depth = m.end(), 1
        while depth and i < len(text):
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        yield text[m.start():i]


def read(path):
    return open(path, encoding='utf-8-sig', errors='replace').read()


def collect_sprites():
    found = {}
    sources = [os.path.join(GAME, 'interface'), os.path.join(UTTNH, 'interface')]
    for root in sources:   # later sources win, as in the game's load order
        for f in sorted(glob.glob(os.path.join(root, '**', '*.gfx'), recursive=True)):
            for b in blocks(read(f), 'spriteType'):
                m = re.search(r'\bname\s*=\s*"?(GFX_GER_[A-Za-z0-9_]+)"?', b)
                if m:
                    found[m.group(1)] = b
    return found


def collect_entities():
    names = set()
    for root in (os.path.join(GAME, 'gfx', 'entities'), os.path.join(UTTNH, 'gfx', 'entities')):
        for f in glob.glob(os.path.join(root, '**', '*.asset'), recursive=True):
            for b in blocks(read(f), 'entity'):
                m = re.search(r'\bname\s*=\s*"(GER_[A-Za-z0-9_]+)"', b)
                if m:
                    names.add(m.group(1))
    return sorted(names)


def main():
    tags = warlord_tags()
    sprites = collect_sprites()
    entities = collect_entities()

    o = ['# GENERATED by tools/gen_rk_german_art.py - do not edit by hand.',
         f'# Every GFX_GER_* sprite (vanilla + UTTNH 3.0, {len(sprites)}) mirrored for the',
         f'# {len(tags)} German Reichskommissariate and protectorates: {" ".join(tags)}.',
         '', 'spriteTypes = {']
    for tag in tags:
        for name, b in sorted(sprites.items()):
            new = name.replace('GFX_GER_', f'GFX_{tag}_', 1)
            body = re.sub(r'(\bname\s*=\s*)"?' + re.escape(name) + r'"?', lambda m: m.group(1) + '"' + new + '"', b, count=1)
            o.append('\t' + body.strip().replace('\n', '\n\t'))
    o.append('}')
    with open(OUT_GFX, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')

    o = ['# GENERATED by tools/gen_rk_german_art.py - do not edit by hand.',
         f'# Every GER_*_entity (vanilla + UTTNH 3.0, {len(entities)}) cloned for the',
         f'# {len(tags)} German Reichskommissariate and protectorates.', '']
    for tag in tags:
        for e in entities:
            o.append(f'entity = {{ name = "{tag}_{e[4:]}" clone = "{e}" }}')
    with open(OUT_ASSET, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')

    for f in OLD:
        if os.path.exists(f):
            os.remove(f)
            print('removed', os.path.relpath(f, MOD))
    print(f'{len(tags)} tags, {len(sprites)} sprites, {len(entities)} entities')
    print('sprite file', os.path.getsize(OUT_GFX) // 1024, 'KB; entity file', os.path.getsize(OUT_ASSET) // 1024, 'KB')


if __name__ == '__main__':
    main()
