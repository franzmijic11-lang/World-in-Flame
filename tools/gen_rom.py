def icon_names():
    names = set()
    for root in (GAME, MOD, UTTNH):
        for fn in glob.glob(os.path.join(root, 'interface', '*.gfx')):
            names |= set(re.findall(r'name\s*=\s*"?(GFX_[A-Za-z0-9_]+)', open(fn, encoding='utf-8', errors='ignore').read()))
    return names


def gen_tree(names, snapshot, tree, prefix, rewards, avail, icons, path, factor):
    m = json.load(open(p('tools', snapshot), encoding='utf-8'))
    m = m.get('data', m)
    by_id = {f['id']: f for f in m['focuses']}
    keys = [f['fid'][len(prefix):] for f in m['focuses']]
    missing = sorted(k for k in keys if k not in rewards)
    assert not missing, f'no reward for {missing}'
    noicon = sorted(k for k in keys if k not in icons)
    assert not noicon, f'no icon for {noicon}'
    bad = sorted(icons[k] for k in keys if icons[k] not in names)
    assert not bad, f'missing icons {bad}'
    maxy = max(f['y'] for f in m['focuses'])
    country = (f'\tcountry = {{\n\t\tfactor = 0\n\t\tmodifier = {{ add = {factor} original_tag = ROM }}\n\t}}' if factor else '\tcountry = {\n\t\tfactor = 0\n\t}')
    o = [HEADER.rstrip('\n'), f'# Layout from the Focus Tree Planner (tools/{snapshot}).', '',
         'focus_tree = {', f'\tid = {tree}', '', country, '',
         '\tdefault = no', '\treset_on_civilwar = no', f'\tcontinuous_focus_position = {{ x = 50 y = {(maxy + 2) * 130} }}', '']
    for f in sorted(m['focuses'], key=lambda f: (f['y'], f['x'])):
        fid = f['fid']
        k = fid[len(prefix):]
        o += ['\tfocus = {', f'\t\tid = {fid}', f'\t\ticon = {icons[k]}']
        if f['pre']:
            ids = [by_id[i]['fid'] for i in f['pre']]
            if f.get('any'):
                o.append('\t\tprerequisite = { ' + ' '.join(f'focus = {i}' for i in ids) + ' }')
            else:
                o += [f'\t\tprerequisite = {{ focus = {i} }}' for i in ids]
        if f['mx']:
            o.append('\t\tmutually_exclusive = { ' + ' '.join(f'focus = {by_id[i]["fid"]}' for i in f['mx']) + ' }')
        o += [f'\t\tx = {f["x"]}', f'\t\ty = {f["y"]}', f'\t\tcost = {cost(f["days"])}']
        if k in avail:
            o.append(f'\t\tavailable = {{ {avail[k]} }}')
        o.append(f'\t\tai_will_do = {{ {AI.get(k, "base = 10")} }}')
        o.append(f'\t\tsearch_filters = {{ {FILTER.get(f["branch"], "FOCUS_FILTER_POLITICAL")} }}')
        o += ['\t\tcompletion_reward = {', indent(rewards[k], 3), '\t\t}', '\t}', '']
    o += ['}', '']
    write(path, '\n'.join(o))
    return m


