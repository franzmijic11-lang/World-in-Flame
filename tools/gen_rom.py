def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


def flavour(desc):
    keep = []
    for para in desc.split('\n\n'):
        if re.match(r"^(Effect|Available|AI|THE |IF |TRANSYLVANIA|FOUR |[0-9]\.|[A-Z][A-Z' ]{3,}[A-Z](?: \(|:| -))", para):
            if keep:
                break
            continue
        keep.append(para.strip())
    return '\n\n'.join(keep)


def gen_loc(maps):
    o = ['l_english:']
    for m in maps:
        for f in m['focuses']:
            o += [f' {f["fid"]}:0 "{esc(f["name"])}"', f' {f["fid"]}_desc:0 "{esc(flavour(f["desc"]))}"']
    for k, (_, _, name, desc) in IDEAS.items():
        o += [f' {k}:0 "{esc(name)}"', f' {k}_desc:0 "{esc(desc)}"']
    for k, v in TT.items():
        o.append(f' {k}:0 "{esc(v)}"')
    tbs = sorted(set(re.findall(r'name = (wif_rom_tb_[a-z0-9_]+) bonus', ' '.join(list(R.values()) + list(RC.values())))))
    for k in tbs:
        o.append(f' {k}:0 "Romanian Focus"')
    keys = [l.split(':')[0].strip() for l in o[1:]]
    dup = {k for k in keys if keys.count(k) > 1}
    assert not dup, f'duplicate loc keys {dup}'
    write('localisation/english/wif_rom_l_english.yml', '\n'.join(o) + '\n', bom=True, crlf=False)


def art():
    from PIL import Image
    src = p('tools', 'art', 'rom', 'groza.webp')
    d = p('gfx', 'leaders', 'ROM')
    os.makedirs(d, exist_ok=True)
    im = Image.open(src).convert('RGBA')
    sw, sh = im.size
    w, h = 156, 210
    if sw / sh > w / h:
        nw = int(sh * w / h)
        x = (sw - nw) // 2
        im = im.crop((x, 0, x + nw, sh))
    else:
        nh = int(sw * h / w)
        im = im.crop((0, 0, sw, nh))
    im.resize((w, h), Image.LANCZOS).save(os.path.join(d, 'Portrait_wif_groza.png'))
    print('wrote gfx/leaders/ROM/Portrait_wif_groza.png')


