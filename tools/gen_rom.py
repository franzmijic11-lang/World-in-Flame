def vp_province(state):
    f = (glob.glob(p('history', 'states', f'{state}-*')) or glob.glob(os.path.join(GAME, 'history', 'states', f'{state}-*')))[0]
    t = re.sub(r'#[^\n]*', '', open(f, encoding='utf-8-sig', errors='ignore').read())
    m = re.search(r'victory_points\s*=\s*\{\s*(\d+)', t) or re.search(r'provinces\s*=\s*\{\s*(\d+)', t)
    return int(m.group(1))


