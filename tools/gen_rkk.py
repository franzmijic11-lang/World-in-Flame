def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


def flavour(desc):
    keep = []
    for para in desc.split('\n\n'):
        if re.match(r"^(Effect:|Available:|AI:|AFTER |[A-Z][A-Z' ]{3,}[A-Z](?: \(|:| -))", para):
            if keep:
                break
            continue
        keep.append(para.strip())
    return '\n\n'.join(keep)


