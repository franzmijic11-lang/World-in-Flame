def mod_lines(mods, n):
    o = []
    for a, b in mods.items():
        if isinstance(b, dict):
            o += ['\t' * n + f'{a} = {{'] + mod_lines(b, n + 1) + ['\t' * n + '}']
        else:
            o.append('\t' * n + f'{a} = {b}')
    return o


