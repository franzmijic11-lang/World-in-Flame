def patch_peace_deal():
    path = p('common', 'scripted_effects', 'wif_peace_deal.txt')
    raw = open(path, 'rb').read()
    s = raw.decode('utf-8')
    if 'wif_can_become_empire' in s:
        print('peace deal already patched')
        return
    nl = '\r\n' if '\r\n' in s else '\n'
    old = '\t\tENG = { wif_peace_hand_over_british_fleet = yes }' + nl
    assert s.count(old) == 1, s.count(old)
    new = old + '\t\tCAN = { wif_can_become_empire = yes }\t# tools/gen_can_empire.py' + nl
    open(path, 'wb').write(s.replace(old, new).encode('utf-8'))
    print('patched wif_peace_deal step 8')


