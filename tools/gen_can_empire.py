def meter(v, n):
    """A change to one of the three meters, shown as its own tooltip line."""
    name, good = METER[v]
    key = f'wif_can_{v}_{"p" if n > 0 else "m"}{abs(n)}_tt'
    col = 'G' if n * good > 0 else 'R'
    TT[key] = f'{name}: §{col}{n:+d}§!'
    return j(f'custom_effect_tooltip = {key}', block('hidden_effect', j(
        f'add_to_variable = {{ wif_can_{v} = {n} }}',
        f'clamp_variable = {{ var = wif_can_{v} min = 0 max = 100 }}')))


