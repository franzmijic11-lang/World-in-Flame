def patch_rk_trigger():
    path = p('common', 'scripted_triggers', 'wif_peace_deal_triggers.txt')
    raw = open(path, 'rb').read().decode('utf-8')
    nl = '\r\n' if '\r\n' in raw else '\n'
    s = raw.replace('\r\n', '\n')
    if 'original_tag = RKS' in s:
        print('wif_is_reichskommissariat already knows RKS')
        return
    old = '\t\t\t\toriginal_tag = RKG\n'
    assert s.count(old) == 1
    s = s.replace(old, old + '\t\t\t\toriginal_tag = RKS\n')
    open(path, 'wb').write(s.replace('\n', nl).encode('utf-8'))
    print('added RKS to wif_is_reichskommissariat')


def patch_art_tags():
    path = p('tools', 'gen_rk_german_art.py')
    s = open(path, encoding='utf-8').read()
    if "'RKS'" in s:
        return
    old = "'RKF', 'RKR', 'RKZ', 'BMP']"
    assert s.count(old) == 1
    open(path, 'w', encoding='utf-8').write(s.replace(old, "'RKF', 'RKR', 'RKZ', 'BMP', 'RKS']"))
    print('added RKS to gen_rk_german_art.py (re-run it)')


