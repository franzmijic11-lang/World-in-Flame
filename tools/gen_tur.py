        if fid.startswith('TUR_'):
            body = vb[fid]
            body = re.sub(r'\n\s*relative_position_id = \w+', '', body)
            body = re.sub(r'\n(\s*)x = -?\d+', f'\n\\1x = {f["x"]}', body, count=1)
