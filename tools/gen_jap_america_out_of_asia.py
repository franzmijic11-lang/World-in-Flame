def gen_focus():
    f = HEADER + f'''# Added to vanilla's japan_wtt_focus by the shared_focus line at the end of
# common/national_focus/japan.txt (a copy of vanilla's, made by the generator).
shared_focus = {{
	id = {FOCUS}
	icon = GFX_focus_JAP_greater_east_asian_co_properity_sphere
	x = {FOCUS_X}
	y = {FOCUS_Y}
	cost = 10

	available = {{
		wif_jap_aooa_ready = yes
	}}

	search_filters = {{ FOCUS_FILTER_POLITICAL FOCUS_FILTER_ANNEXATION }}

	ai_will_do = {{
		base = 100
	}}

	completion_reward = {{
		custom_effect_tooltip = wif_jap_aooa_peace_tt
		hidden_effect = {{ wif_jap_aooa_peace = yes }}
	}}
}}
'''
    write('common/national_focus/wif_jap_aooa_focus.txt', f)

    src = open(os.path.join(GAME, 'common', 'national_focus', 'japan.txt'), 'rb').read().decode('utf-8-sig')
    assert '\r\n' not in src
    i = src.rstrip().rfind('}')
    line = f'\n\t# Welt in Flammen (tools/gen_jap_america_out_of_asia.py)\n\tshared_focus = {FOCUS}\n'
    out = src[:i].rstrip('\n') + '\n' + line + src[i:]
    # vanilla's own bytes otherwise: BOM and LF kept as shipped
    with open(p('common', 'national_focus', 'japan.txt'), 'w', encoding='utf-8-sig', newline='') as fh:
        fh.write(out)
    print('wrote common/national_focus/japan.txt (vanilla copy + shared focus)')


