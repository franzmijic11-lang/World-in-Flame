"""Writes common/scripted_effects/wif_inherit_special_projects_from_donor.txt:
one effect that completes, in the current scope, every special project
event_target:wif_tech_donor has completed. The companion of
wif_inherit_tech_from_donor - set the donor first, then call both.

Projects are read from common/special_projects/projects/*.txt in vanilla, then
UTTNH 3.0, then WiF; a later file with the same name replaces an earlier one,
as the game loads them.

Rerun when the mod stack changes:  python tools/gen_special_project_inherit.py
"""
import os
import re

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOTS = [
    r"C:/Program Files (x86)/Steam/steamapps/common/Hearts of Iron IV",
    r"C:/Program Files (x86)/Steam/steamapps/workshop/content/394360/3413890094",  # UTTNH 3.0
    MOD,
]
OUT = os.path.join(MOD, 'common', 'scripted_effects', 'wif_inherit_special_projects_from_donor.txt')


def top_level_keys(text):
    text = re.sub(r'#[^\n]*', '', text)
    keys, depth, i = [], 0, 0
    for m in re.finditer(r'[{}]|([A-Za-z0-9_]+)\s*=\s*\{', text):
        if m.group(1):
            if depth == 0:
                keys.append(m.group(1))
            depth += 1
        elif m.group(0) == '{':
            depth += 1
        else:
            depth -= 1
    return keys


files = {}
for root in ROOTS:
    d = os.path.join(root, 'common', 'special_projects', 'projects')
    if os.path.isdir(d):
        for f in os.listdir(d):
            if f.endswith('.txt'):
                files[f] = os.path.join(d, f)

projects = []
for f in sorted(files):
    with open(files[f], encoding='utf-8-sig', errors='replace') as fh:
        projects += [k for k in top_level_keys(fh.read()) if k not in projects]

lines = [
    '# GENERATED by tools/gen_special_project_inherit.py - do not edit by hand.',
    '#',
    '# Completes in the current scope every special project that',
    '# event_target:wif_tech_donor has completed. Set the donor first:',
    '#',
    '#     GER = { save_event_target_as = wif_tech_donor }',
    '#     SPG = { wif_inherit_special_projects_from_donor = yes }',
    '#',
    '# complete_special_project skips the facility and scientist effects, which',
    '# is right for a successor inheriting finished work.',
    '',
    'wif_inherit_special_projects_from_donor = {',
]
for p in projects:
    lines.append(f'\tif = {{ limit = {{ event_target:wif_tech_donor = {{ is_special_project_completed = sp:{p} }} '
                 f'NOT = {{ is_special_project_completed = sp:{p} }} }} complete_special_project = sp:{p} }}')
lines.append('}')
lines.append('')
with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('\n'.join(lines))
print(f'{len(projects)} special projects from {len(files)} files')
