"""Japan's dictated peace in China - fires the moment China surrenders.

Source of truth for everything listed in main() below. Run:

    python tools/gen_jap_china_peace.py

Design (the user's spec, 2026-11-08):
  Fires (on_capitulation_immediate, once per game) when a country at war with
  Japan capitulates and
    - the Chinese United Front exists (any faction on
      faction_template_chinese_united_front): it is the United Front's leader
    - otherwise: it is Nationalist China, or it owns both Nanjing and
      Chongqing (a warlord holding the KMT's heartland)
  Then, with no peace conference:
    - Japan, its subjects and its faction white-peace every Chinese country.
      Japan's wars with anyone else go on.
    - Every Chinese country (CHI, PRC, every vanilla is_chinese_warlord tag,
      every United Front member) that is not on Japan's side makes peace with
      all its enemies and leaves its faction; the United Front is dissolved.
    - Only from owners at war with Japan:
        the Chinese coast, Nanjing, Hebei-Chahar and Guangxi's
        1936 land (Hainan included)                          -> Japan
        the RNG list below and the five states it encloses   -> RNG,
                                                                Imperial Associate
      RNG-list states Japan itself owns go to RNG too.
    - The Shandong Clique and Hebei-Chahar Council, if they exist, are annexed
      by Japan.
    - Warlords that no longer exist (YUN, SHX, XSM, SIK; GXC's land is all
      Japanese) are re-formed on their 1936 states that a Chinese country
      still holds. Land owned by Japan, RNG or Japan's other subjects counts
      as Japanese and is not given back.
    - Every Chinese warlord left afterwards (re-formed ones included; not CHI
      or PRC) gets wif_splinter_no_factions, "No Diplomatic Standing".
  Console test: event wif_debug.18 runs the settlement now, without the
  surrender.
"""
import os

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = '# GENERATED by tools/gen_jap_china_peace.py - edit the generator, not this file.\n\n'
CUF = 'faction_template_chinese_united_front'

TO_JAP = {
    # Nationalist coast
    595: 'Fujian', 596: 'Zhejiang', 597: 'Shandong', 743: 'Qingdao', 1038: 'Jinan', 598: 'Jiangsu',
    1034: 'Suzhou', 613: 'Shanghai', 614: 'Hebei', 608: 'Beiping',
    # Nanjing and Hebei-Chahar
    1035: 'Nanjing', 1039: 'Hebei-Chahar',
    # Guangxi Clique's 1936 land
    591: 'Hainan', 592: 'Guangzhou', 593: 'Guangdong', 594: 'Nanning', 599: 'Guangxi', 1033: 'Leizhou',
}
TO_RNG = {
    600: 'Jiangxi', 749: 'Huangshan', 606: 'Anhui', 607: 'Henan', 615: 'Shanxi', 602: 'Hunan',
    603: 'Guizhou', 325: 'Yunnan', 751: 'Liangshan', 1041: 'Chengdu', 605: 'Sichuan', 744: 'Xian',
    # enclosed by the above
    620: 'Hubei', 1036: 'Wuhan', 750: 'Changde', 748: 'Zunyi', 1037: 'Chongqing',
}
RNG_CAPITALS = [1036, 620, 1037, 605, 607]       # Wuhan first; Nanjing and Shanghai are Japan's now

# Warlords that come back if destroyed: 1936 states, capital first.
WARLORDS = {
    'GXC': [594, 591, 592, 593, 599, 1033],
    'YUN': [325, 747],
    'SHX': [615, 621, 746],
    'XSM': [754, 283, 604, 616, 753, 755, 756, 1040, 1044, 1045],
    'SIK': [617, 287, 618, 619, 759, 760, 1042],
}
ANNEXED_TAGS = ['SND', 'HBC']

assert not set(TO_JAP) & set(TO_RNG)


def write(rel, text, bom=False, crlf=True):
    path = os.path.join(MOD, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if crlf:
        text = text.replace('\r\n', '\n').replace('\n', '\r\n')
    with open(path, 'w', encoding='utf-8-sig' if bom else 'utf-8', newline='') as f:
        f.write(text)
    print('wrote', rel)


def ors(ids):
    return 'OR = { ' + ' '.join(f'state = {i}' for i in ids) + ' }'


def names(d):
    return ', '.join(d.values())


# ------------------------------------------------------------------ triggers
def gen_triggers():
    write('common/scripted_triggers/wif_jap_china_peace_triggers.txt', HEADER + f'''# Scope: the country that just capitulated.
wif_jap_china_peace_fires = {{
	NOT = {{ has_global_flag = wif_jap_china_peace }}
	country_exists = JAP
	has_war_with = JAP
	OR = {{
		AND = {{
			is_faction_leader = yes
			has_faction_template = {CUF}
		}}
		AND = {{
			NOT = {{ any_country = {{ has_faction_template = {CUF} }} }}
			OR = {{
				original_tag = CHI
				AND = {{
					owns_state = 1035
					owns_state = 1037
				}}
			}}
		}}
	}}
}}

# Scope: any country. Chinese and not on Japan's side.
wif_jap_china_peace_is_chinese = {{
	NOT = {{ original_tag = JAP }}
	NOT = {{ is_subject_of = JAP }}
	NOT = {{ is_in_faction_with = JAP }}
	OR = {{
		original_tag = CHI
		original_tag = PRC
		is_chinese_warlord = yes
		has_faction_template = {CUF}
	}}
}}
''')


# ------------------------------------------------------------------ effects
def gen_effects():
    t = HEADER + f'''# JAP scope. Japan's dictated peace in China.
wif_jap_china_peace = {{
	set_global_flag = wif_jap_china_peace
	set_global_flag = wif_jap_beat_china

	# 1. The sides, read before any peace is made.
	every_country = {{
		limit = {{ has_war_with = JAP }}
		set_country_flag = wif_jcp_enemy
	}}
	every_country = {{
		limit = {{ wif_jap_china_peace_is_chinese = yes }}
		set_country_flag = wif_jcp_chinese
	}}
'''
    for tag in WARLORDS:
        t += f'''	if = {{
		limit = {{ NOT = {{ country_exists = {tag} }} }}
		set_global_flag = wif_jcp_reform_{tag}
	}}
'''
    t += f'''
	# 2. What changes hands - only land whose owner is at war with Japan.
	#    Japan: {names(TO_JAP)}
	every_state = {{
		limit = {{
			{ors(TO_JAP)}
			OWNER = {{ has_country_flag = wif_jcp_enemy }}
		}}
		set_state_flag = wif_jcp_to_JAP
	}}
	#    RNG: {names(TO_RNG)}
	every_state = {{
		limit = {{
			{ors(TO_RNG)}
			OWNER = {{
				OR = {{
					has_country_flag = wif_jcp_enemy
					tag = JAP
				}}
			}}
		}}
		set_state_flag = wif_jcp_to_RNG
	}}

	# 3. Japan's side makes peace with the Chinese, and only with them.
	every_country = {{
		limit = {{
			OR = {{
				tag = JAP
				is_subject_of = JAP
				is_in_faction_with = JAP
			}}
		}}
		every_enemy_country = {{
			limit = {{ has_country_flag = wif_jcp_chinese }}
			PREV = {{ white_peace = PREV }}
		}}
	}}

	# 4. Every Chinese country makes peace with all its enemies and leaves its
	#    faction. The United Front's leader dismantles it.
	every_country = {{
		limit = {{ has_country_flag = wif_jcp_chinese }}
		every_enemy_country = {{
			PREV = {{ white_peace = PREV }}
		}}
	}}
	every_country = {{
		limit = {{
			has_country_flag = wif_jcp_chinese
			is_faction_leader = yes
		}}
		dismantle_faction = yes
	}}
	every_country = {{
		limit = {{
			has_country_flag = wif_jcp_chinese
			is_in_faction = yes
		}}
		leave_faction = yes
	}}

	# 5. The land changes hands, now that nobody is at war over it.
	every_state = {{
		limit = {{ has_state_flag = wif_jcp_to_JAP }}
		clr_state_flag = wif_jcp_to_JAP
		transfer_state_to = JAP
	}}
'''
    for tag in ANNEXED_TAGS:
        t += f'''	if = {{
		limit = {{ country_exists = {tag} }}
		JAP = {{ annex_country = {{ target = {tag} transfer_troops = no }} }}
	}}
'''
    t += '''	every_state = {
		limit = { has_state_flag = wif_jcp_to_RNG }
		clr_state_flag = wif_jcp_to_RNG
		add_core_of = RNG
		transfer_state_to = RNG
	}
	if = {
		limit = { country_exists = RNG }
		RNG = {
'''
    for i, s in enumerate(RNG_CAPITALS):
        kw = 'if' if i == 0 else 'else_if'
        t += f'\t\t\t{kw} = {{ limit = {{ owns_state = {s} }} set_capital = {{ state = {s} }} }}\n'
    t += '''			if = {
				limit = { country_exists = CHI }
				inherit_technology = CHI
			}
		}
		if = {
			limit = { NOT = { RNG = { is_subject_of = JAP } } }
			puppet = RNG
		}
		set_autonomy = {
			target = RNG
			autonomous_state = autonomy_wtt_imperial_associate
			end_wars = no
			end_civil_wars = no
		}
	}

	# 6. Destroyed warlords come back on land a Chinese country still holds.
'''
    for tag, states in WARLORDS.items():
        t += f'''	if = {{
		limit = {{ has_global_flag = wif_jcp_reform_{tag} }}
		clr_global_flag = wif_jcp_reform_{tag}
		every_state = {{
			limit = {{
				{ors(states)}
				OWNER = {{ has_country_flag = wif_jcp_chinese }}
			}}
			transfer_state_to = {tag}
		}}
		if = {{
			limit = {{ country_exists = {tag} }}
			{tag} = {{
'''
        for i, s in enumerate(states):
            kw = 'if' if i == 0 else 'else_if'
            t += f'\t\t\t\t{kw} = {{ limit = {{ owns_state = {s} }} set_capital = {{ state = {s} }} }}\n'
        t += '''			}
		}
	}
'''
    t += '''
	# 7. Every warlord still standing, re-formed ones included, has no
	#    diplomatic standing - the splinter-state spirit the Russian warlords
	#    get (no factions, guarantees, volunteers or lend-lease).
	every_country = {
		limit = {
			is_chinese_warlord = yes
			wif_jap_china_peace_is_chinese = yes
			NOT = { has_idea = wif_splinter_no_factions }
		}
		add_ideas = wif_splinter_no_factions
	}

	every_country = {
		limit = {
			OR = {
				has_country_flag = wif_jcp_enemy
				has_country_flag = wif_jcp_chinese
			}
		}
		clr_country_flag = wif_jcp_enemy
		clr_country_flag = wif_jcp_chinese
	}

	every_country = {
		news_event = { id = wif_jap_china_peace.1 days = 1 }
	}
}
'''
    write('common/scripted_effects/wif_jap_china_peace_effects.txt', t)


# ------------------------------------------------------------------ on_actions, events, loc
def gen_misc():
    write('common/on_actions/wif_jap_china_peace_on_actions.txt', HEADER + '''on_actions = {
	# ROOT is the capitulated country, FROM the winner. _immediate runs before
	# the game decides on a peace conference, so the white peace pre-empts it.
	on_capitulation_immediate = {
		effect = {
			if = {
				limit = { wif_jap_china_peace_fires = yes }
				JAP = { wif_jap_china_peace = yes }
			}
		}
	}
}
''')
    write('events/wif_jap_china_peace.txt', HEADER + '''add_namespace = wif_jap_china_peace

# Japan's dictated peace in China, to the whole world.
news_event = {
	id = wif_jap_china_peace.1
	title = wif_jap_china_peace.1.t
	desc = wif_jap_china_peace.1.d
	picture = GFX_news_event_japanese_parade

	major = yes
	is_triggered_only = yes

	option = {
		name = wif_jap_china_peace.1.a
		trigger = { tag = JAP }
	}
	option = {
		name = wif_jap_china_peace.1.b
		trigger = { wif_jap_china_peace_is_chinese = yes }
	}
	option = {
		name = wif_jap_china_peace.1.c
		trigger = {
			NOT = { tag = JAP }
			NOT = { wif_jap_china_peace_is_chinese = yes }
		}
	}
}
''')
    L = {
        'wif_jap_china_peace.1.t': 'Japan Dictates Peace in China',
        'wif_jap_china_peace.1.d': 'With the surrender of its government, China\'s war with Japan is over, and there was no conference to end it. Tokyo has annexed the Chinese coast from Hebei to Hainan, Nanjing among it, along with all of Guangdong and Guangxi. The heartland of the interior, from Henan and Shanxi to Sichuan and Yunnan, passes to Wang Jingwei\'s Reorganized National Government as an Imperial Associate of Japan. Whatever Chinese governments are left have laid down their arms against all comers, and the United Front is no more.',
        'wif_jap_china_peace.1.a': 'The China Incident is closed.',
        'wif_jap_china_peace.1.b': 'We will not forget this humiliation.',
        'wif_jap_china_peace.1.c': 'Asia has a new master.',
    }
    write('localisation/english/wif_jap_china_peace_l_english.yml',
          'l_english:\n' + ''.join(f' {k}:0 "{v}"\n' for k, v in L.items()), bom=True, crlf=False)


def main():
    gen_triggers()
    gen_effects()
    gen_misc()


if __name__ == '__main__':
    main()
