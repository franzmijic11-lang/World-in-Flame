"""Soviet tech icons, equipment art and 3D unit models for every Russian warlord.

HoI4 looks art up by tag first: equipment and tech pictures as
GFX_<TAG>_<name>, unit models as <TAG>_<name>_entity, falling back to the
graphical culture only when no tagged one exists. So every GFX_SOV_* sprite
and every SOV_*_entity - from vanilla AND from Ultimate Tech Tree: New Horizons
3.0, which keeps most of its Soviet art in interface/replace/ - gets a twin for
each warlord tag:
  * sprites: a copy of the SOV block with the tag swapped in the name (same
    texture files, so no art is duplicated on disk)
  * entities: `clone = "SOV_..._entity"`, which vanilla and UTTNH both use
    across files

The tags are read from wif_is_russian_warlord in
common/scripted_triggers/wif_scripted_triggers.txt, so a warlord added there
gets the art on the next run. RE-RUN after adding a warlord or updating UTTNH.

Replaces the hand-made SME-only files from the UTTNH 2.0 days
(interface/SME_unit_sprites.gfx, gfx/entities/zz_SME_units.asset), which it
deletes.

Writes:
  interface/zz_wif_warlord_sov_sprites.gfx
  gfx/entities/zz_wif_warlord_sov_units.asset
"""
import glob
import os
import re

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = r'C:\Program Files (x86)\Steam\steamapps\common\Hearts of Iron IV'
UTTNH = r'C:\Program Files (x86)\Steam\steamapps\workshop\content\394360\3413890094'
OUT_GFX = os.path.join(MOD, 'interface', 'zz_wif_warlord_sov_sprites.gfx')
OUT_ASSET = os.path.join(MOD, 'gfx', 'entities', 'zz_wif_warlord_sov_units.asset')
OLD = [os.path.join(MOD, 'interface', 'SME_unit_sprites.gfx'),
       os.path.join(MOD, 'gfx', 'entities', 'zz_SME_units.asset')]


def warlord_tags():
    s = open(os.path.join(MOD, 'common', 'scripted_triggers', 'wif_scripted_triggers.txt'), encoding='utf-8').read()
    s = re.sub(r'#.*', '', s)
    m = re.search(r'wif_is_russian_warlord\s*=\s*\{', s)
    i, depth = m.end(), 1
    while depth:
        depth += {'{': 1, '}': -1}.get(s[i], 0)
        i += 1
    return re.findall(r'tag\s*=\s*([A-Z0-9]{3})', s[m.end():i])


def blocks(text, keyword):
    """Yield every balanced `keyword = { ... }` block (case-insensitive)."""
    text = re.sub(r'#[^\n]*', '', text)
    for m in re.finditer(r'\b' + keyword + r'\s*=\s*\{', text, re.I):
        i, depth = m.end(), 1
        while depth and i < len(text):
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        yield text[m.start():i]


def read(path):
    return open(path, encoding='utf-8-sig', errors='replace').read()


def collect_sprites():
    found = {}
    sources = [os.path.join(GAME, 'interface'), os.path.join(UTTNH, 'interface')]
    for root in sources:   # later sources win, as in the game's load order
        for f in sorted(glob.glob(os.path.join(root, '**', '*.gfx'), recursive=True)):
            for b in blocks(read(f), 'spriteType'):
                m = re.search(r'\bname\s*=\s*"?(GFX_SOV_[A-Za-z0-9_]+)"?', b)
                if m:
                    found[m.group(1)] = b
    return found


def collect_entities():
    names = set()
    for root in (os.path.join(GAME, 'gfx', 'entities'), os.path.join(UTTNH, 'gfx', 'entities')):
        for f in glob.glob(os.path.join(root, '**', '*.asset'), recursive=True):
            for b in blocks(read(f), 'entity'):
                m = re.search(r'\bname\s*=\s*"(SOV_[A-Za-z0-9_]+)"', b)
                if m:
                    names.add(m.group(1))
    return sorted(names)


def main():
    tags = warlord_tags()
    sprites = collect_sprites()
    entities = collect_entities()

    o = ['# GENERATED by tools/gen_warlord_soviet_art.py - do not edit by hand.',
         f'# Every GFX_SOV_* sprite (vanilla + UTTNH 3.0, {len(sprites)}) mirrored for the',
         f'# {len(tags)} Russian warlords: {" ".join(tags)}.',
         '', 'spriteTypes = {']
    for tag in tags:
        for name, b in sorted(sprites.items()):
            new = name.replace('GFX_SOV_', f'GFX_{tag}_', 1)
            body = re.sub(r'(\bname\s*=\s*)"?' + re.escape(name) + r'"?', lambda m: m.group(1) + '"' + new + '"', b, count=1)
            o.append('\t' + body.strip().replace('\n', '\n\t'))
    o.append('}')
    with open(OUT_GFX, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')

    o = ['# GENERATED by tools/gen_warlord_soviet_art.py - do not edit by hand.',
         f'# Every SOV_*_entity (vanilla + UTTNH 3.0, {len(entities)}) cloned for the',
         f'# {len(tags)} Russian warlords.', '']
    for tag in tags:
        for e in entities:
            o.append(f'entity = {{ name = "{tag}_{e[4:]}" clone = "{e}" }}')
    with open(OUT_ASSET, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')

    for f in OLD:
        if os.path.exists(f):
            os.remove(f)
            print('removed', os.path.relpath(f, MOD))
    print(f'{len(tags)} tags, {len(sprites)} sprites, {len(entities)} entities')
    print('sprite file', os.path.getsize(OUT_GFX) // 1024, 'KB; entity file', os.path.getsize(OUT_ASSET) // 1024, 'KB')


if __name__ == '__main__':
    main()
