def flavour(desc):
    keep = []
    for para in desc.split('\n\n'):
        para = re.sub(r'^AUTO-COMPLETES \(consequence\)\.\s*', '', para)
        if re.match(r"^(Effect:|AFTER |[A-Z][A-Z' ]{3,}[A-Z](?: \(|:| -))", para):
            if keep:
                break
            continue
        keep.append(para.strip())
    return '\n\n'.join(keep)


