def splice_lists():
    # warlord trigger
    rel = 'common/scripted_triggers/wif_scripted_triggers.txt'
    s = open(p(rel), 'rb').read().decode('utf-8')
    nl = '\r\n' if '\r\n' in s else '\n'
    start, end = '\t\t# >>> Siberian collapse (tools/gen_siberia_collapse.py)', '\t\t# <<< Siberian collapse'
    block = nl.join([start] + [f'\t\ttag = {n["tag"]}' for n in NEW] + [end])
    if start in s:
        s = re.sub(re.escape(start) + r'.*?' + re.escape(end), lambda _: block, s, flags=re.S)
    else:
        anchor = '\t\ttag = SPT' + nl + '\t}' + nl + '}'
        assert s.count(anchor) == 1, 'warlord trigger anchor'
        s = s.replace(anchor, '\t\ttag = SPT' + nl + nl + block + nl + '\t}' + nl + '}')
    open(p(rel), 'wb').write(s.encode('utf-8'))
    print('spliced', rel)
    # blank tree
    rel = 'common/national_focus/wif_breakaway_blank.txt'
    s = open(p(rel), 'rb').read().decode('utf-8')
    nl = '\r\n' if '\r\n' in s else '\n'
    for n in NEW:
        line = f'\t\t\t\ttag = {n["tag"]}'
        if line not in s:
            anchor = '\t\t\t\ttag = CRA' + nl
            assert anchor in s, 'blank tree anchor'
            s = s.replace(anchor, anchor + line + nl, 1)
    open(p(rel), 'wb').write(s.encode('utf-8'))
    print('spliced', rel)


