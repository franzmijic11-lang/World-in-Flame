"""Capitals that become cities - the terrain half of "The Capital Rises".

HoI4 cannot change a province's terrain during a game: terrain is read once
from map/definition.csv at startup and no effect touches it. So the change is
made the other way round:

  * map/definition.csv (a full copy of vanilla's) marks the provinces below
    urban from 1936.
  * At game start each one gets a hidden "not yet a city" province modifier
    that makes it fight like its old terrain.
  * wif_raise_capital_city (country scope, for the focus) removes that
    modifier from the capital, which leaves it genuinely urban.

What the disguise cannot hide: the terrain tooltip says Urban from the start,
and combat width is urban (80) rather than forest 60 / plains 70.

The battalion cap's city province count (tools/city_provinces.py) reads
VANILLA's definition.csv on purpose, so these provinces do not count as cities
until raised; wif_raise_capital_city adds them to wif_city_provs then.

RE-RUN THIS AFTER EVERY HOI4 PATCH that changes the map: map/definition.csv is
a full override, and a stale copy breaks the game.

Writes:
  map/definition.csv
  common/modifiers/wif_capital_city_modifiers.txt
  common/scripted_effects/wif_capital_city.txt
  localisation/english/wif_capital_city_l_english.yml
"""
import os

GAME = r'C:\Program Files (x86)\Steam\steamapps\common\Hearts of Iron IV'
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# province: (state, name, terrain it really has in vanilla)
# The victory point provinces of the SME collapse capitals that are not urban
# in vanilla. Gorky, Perm and Samara already are; Orenburg (SPT, state 652)
# has no victory point at all and is not handled here.
CITIES = {
    6124:  (400,  'Kirov',     'plains'),   # RUE
    9131:  (351,  'Vologda',   'forest'),   # VGD
    11170: (1085, 'Gayny',     'forest'),   # OSG
    108:   (397,  'Syktyvkar', 'forest'),   # KMR
    12187: (1084, 'Solikamsk', 'forest'),   # RNS
}

# Urban against the real terrain (common/terrain/00_terrain.txt):
#   urban   move 1.2  attack -0.30  supply flow -0.20  truck attrition 0
#   plains  move 1.0  attack  0     supply flow  0     truck attrition 0
#   forest  move 1.5  attack -0.15  supply flow +0.08  truck attrition 0.2
# The modifier puts back the difference. Air superiority (urban -0.5) and
# combat width have no province modifier and stay urban.
DISGUISE = {
    'plains': [
        ('army_attack_factor', '0.3'),
        ('army_speed_factor', '0.2'),
        ('supply_factor', '-0.15'),
    ],
    'forest': [
        ('army_attack_factor', '0.15'),
        ('army_speed_factor', '-0.2'),
        ('supply_factor', '-0.25'),
        ('truck_attrition_factor', '0.2'),
    ],
}


def write(rel, text, bom=False, nl='\r\n'):
    p = os.path.join(MOD, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    data = text.replace('\r\n', '\n').replace('\n', nl).encode('utf-8')
    open(p, 'wb').write((b'\xef\xbb\xbf' if bom else b'') + data)
    print('wrote', rel)


def gen_definition():
    raw = open(os.path.join(GAME, 'map', 'definition.csv'), 'rb').read()
    lines = raw.split(b'\n')
    done = set()
    for i, line in enumerate(lines):
        f = line.rstrip(b'\r').split(b';')
        if len(f) >= 7 and f[0].isdigit() and int(f[0]) in CITIES:
            pid = int(f[0])
            want = CITIES[pid][2].encode()
            assert f[6] == want, f'province {pid} is {f[6]!r} in vanilla, expected {want!r} - recheck CITIES'
            f[6] = b'urban'
            lines[i] = b';'.join(f) + (b'\r' if line.endswith(b'\r') else b'')
            done.add(pid)
    assert done == set(CITIES), f'missing provinces {set(CITIES) - done}'
    p = os.path.join(MOD, 'map', 'definition.csv')
    open(p, 'wb').write(b'\n'.join(lines))
    print('wrote map/definition.csv,', len(done), 'provinces made urban')


def mod_name(terrain):
    return f'wif_not_yet_a_city_{terrain}'


def gen_modifiers():
    o = ['# GENERATED by tools/gen_capital_cities.py - do not edit by hand.',
         '#',
         '# On a province: the town is urban on the map but fights like the ground',
         '# it really is, until wif_raise_capital_city removes this.',
         '']
    for t, mods in DISGUISE.items():
        o.append(f'{mod_name(t)} = {{')
        for k, v in mods:
            o.append(f'\t{k} = {v}')
        o.append('}')
        o.append('')
    write('common/modifiers/wif_capital_city_modifiers.txt', '\n'.join(o))


def gen_effects():
    o = ['# GENERATED by tools/gen_capital_cities.py - do not edit by hand.',
         '#',
         '# The provinces below are urban in map/definition.csv. These effects hide',
         '# that until the town is raised into a city.',
         '',
         '# Any scope. Once per game, from on_startup.',
         'wif_disguise_future_cities = {',
         '\tif = {',
         '\t\tlimit = { NOT = { has_global_flag = wif_future_cities_disguised } }',
         '\t\tset_global_flag = wif_future_cities_disguised']
    for pid, (sid, name, t) in CITIES.items():
        o.append(f'\t\t{sid} = {{ add_province_modifier = {{ static_modifiers = {{ {mod_name(t)} }} province = {pid} }} }}\t# {name}')
    o += ['\t}', '}', '',
          '# Country scope. The capital, if it is one of the towns above and not yet',
          '# raised, becomes the urban province the map already says it is. Also',
          '# counts it as a city for the battalion cap (wif_city_provs).',
          '# Does nothing for any other capital.',
          'wif_raise_capital_city = {',
          '\tcapital_scope = {']
    first = True
    for pid, (sid, name, t) in CITIES.items():
        kw = 'if' if first else 'else_if'
        first = False
        o += [f'\t\t{kw} = {{',
              f'\t\t\tlimit = {{ state = {sid} NOT = {{ has_state_flag = wif_city_raised }} }}\t# {name}',
              f'\t\t\tremove_province_modifier = {{ static_modifiers = {{ {mod_name(t)} }} province = {pid} }}',
              '\t\t\tset_state_flag = wif_city_raised',
              '\t\t\tadd_to_variable = { wif_city_provs = 1 }',
              '\t\t}']
    o += ['\t}',
          '\twif_recalculate_battalion_cap = yes',
          '}', '']
    write('common/scripted_effects/wif_capital_city.txt', '\n'.join(o))


def gen_loc():
    o = ['l_english:']
    for t in DISGUISE:
        o.append(f' {mod_name(t)}:0 "Not Yet a City"')
        o.append(f' {mod_name(t)}_desc:0 "The town is still a garrison town among the {"fields" if t == "plains" else "forests"}. Until it is raised into a real city it fights like the {t} around it."')
    write('localisation/english/wif_capital_city_l_english.yml', '\n'.join(o) + '\n', bom=True)


if __name__ == '__main__':
    gen_definition()
    gen_modifiers()
    gen_effects()
    gen_loc()
