def gen_portraits():
    sprites = []
    for key, (_name, spr) in CANDS.items():
        if spr:
            continue
        src = next((p('tools', 'art', 'usa', key + ext) for ext in ('.jpg', '.png')
                    if os.path.exists(p('tools', 'art', 'usa', key + ext))), None)
        if not src:
            continue
        img = Image.open(src).convert('RGB')
        sw, sh = img.size
        w, h = 156, 210
        if sw / sh > w / h:
            nw = int(sh * w / h)
            x = (sw - nw) // 2
            img = img.crop((x, 0, x + nw, sh))
        else:
            nh = int(sw * h / w)
            y = int((sh - nh) * 0.2)
            img = img.crop((0, y, sw, y + nh))
        img = img.resize((w, h), Image.LANCZOS)
        rel = f'gfx/leaders/USA/Portrait_USA_wif_{key}.png'
        os.makedirs(os.path.dirname(p(rel)), exist_ok=True)
        img.save(p(rel))
        print('wrote', rel)
        sprites.append(f'\tspriteType = {{\n\t\tname = "{sprite(key)}"\n\t\ttexturefile = "{rel}"\n\t}}')
    write('interface/wif_usa_portraits.gfx', HEADER + 'spriteTypes = {\n' + '\n'.join(sprites) + '\n}\n')


