"""American elections 1936-1954 (wif_ue_*): a state-by-state campaign in the
decisions menu, real candidates, winner-take-all states, Congress seats that
are Democratic or Republican.

Source of truth for everything main() writes:

    python tools/gen_usa_elections.py

Design (agreed with the user 2026-11-10):
  * Every presidential election (1936-1952) and midterm (1938-1954) has a
    CAMPAIGN: it opens 1 year before a presidential election and 6 months
    before a midterm. Before each one the player picks the party they lead
    (1936 is forced Democratic - FDR). The AI runs the other party.
  * Presidential years: the player picks BOTH parties' nominees (Convention
    events) when a party has more than one candidate. Only candidates with a
    portrait can run: drop tools/art/usa/<key>.jpg|png and re-run to add one.
  * Every state has a hidden lean 0-100 (0 = solid Democratic, 100 = solid
    Republican): <20 Strong D, 20-40 D, 40-60 Fence, 60-80 R, >80 Strong R.
    Leans persist between elections; only campaigns and focuses move them.
  * Sway State: state-targeted decision, 30 days, 200 PP (20 PP in 1936),
    at most 4 at once. Nobody can campaign in a state that strongly backs
    them already. The AI party runs 2 at a time, at most 4 in the 1936
    campaign and 10 in every later one, aiming at fence states, then the
    other party's leaning states, weighted by electoral votes.
  * Election day: non-fence states are called at once; fence states are
    counted one by one (25% a day each) and the result waits for all of them.
  * Winner-take-all: the state's winner takes all its electoral votes and all
    its House seats. The Senate is elected a third at a time (real classes).
    House seats follow the census (1930 / 1940 / 1950 apportionment).
  * The winning nominee becomes president. Midterms only change Congress.
  * FDR dies in office on 12 April 1945 if he is president; Truman succeeds.
  * Only the 48 states vote. Alaska and Hawaii join through the statehood
    decisions (vanilla's, kept in a WiF copy of MTG_congress.txt). Lost states
    keep their seats (known limitation).
  * Vanilla's Congress panel stays: senators_support / representatives_support
    now mean "seats held by the president's party", recomputed every month,
    so vanilla congress triggers and our focus triggers read real seats.

Map: New England is ONE map state (357) for six voting states - a campaign
there moves all six. Delaware has no map state and rides with Maryland (361).
"""
