def minus_days(d, n):
    import datetime
    y, m, dd = map(int, d.split('.'))
    t = datetime.date(y, m, dd) - datetime.timedelta(days=n)
    return f'{t.year}.{t.month}.{t.day}'


def lean_of(m):
    """1936 margin -> starting lean (0 = solid D, 100 = solid R)."""
    a = abs(m)
    if a > 20:
        l = max(3.0, 19.5 - (a - 20) / 4)
    elif a >= 5:
        l = 39.5 - (a - 5) * 19.5 / 15
    else:
        l = 50 - a * 2
    l = round(l, 1)
    return l if m >= 0 else round(100 - l, 1)


