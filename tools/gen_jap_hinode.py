def splice_debug():
    path = p('events', 'wif_sme_war.txt')
    raw = open(path, 'rb').read()
    bom = raw.startswith(b'\xef\xbb\xbf')
    text = raw.decode('utf-8-sig')
    nl = '\r\n' if '\r\n' in text else '\n'
    if 'wif_debug.19' in text:
        return
    note = ('#   event wif_debug.18   Japan\'s dictated peace in China right now, without' + nl +
            '#                       China\'s surrender' + nl)
    assert note in text
    text = text.replace(note, note + '#   event wif_debug.19   Japan becomes Hinode no Teikoku now (New Asian' + nl +
                        '#                       Hegemon\'s effect, without the focus or its conditions)' + nl)
    block = (nl + 'country_event = {' + nl + '\tid = wif_debug.19' + nl + '\thidden = yes' + nl +
             '\tis_triggered_only = yes' + nl + nl + '\timmediate = {' + nl + '\t\tif = {' + nl +
             '\t\t\tlimit = { country_exists = JAP }' + nl + '\t\t\tJAP = { wif_jap_new_asian_hegemon = yes }' + nl +
             '\t\t}' + nl + '\t}' + nl + '}' + nl)
    text = text.rstrip('\r\n') + nl + block
    open(path, 'wb').write(((b'\xef\xbb\xbf' if bom else b'') + text.encode('utf-8')))
    print('spliced wif_debug.19 into events/wif_sme_war.txt')


# ------------------------------------------------------------------ cosmetic tag
def gen_cosmetic():
    path = p('common', 'countries', 'cosmetic.txt')
    raw = open(path, 'rb').read()
    assert not raw.startswith(b'\xef\xbb\xbf'), 'cosmetic.txt must not have a BOM'
    text = raw.decode('utf-8')
    nl = '\r\n' if '\r\n' in text else '\n'
    block = (f'# WiF: Japan after New Asian Hegemon (tools/gen_jap_hinode.py), #ae2d20.{nl}'
             f'{COSMETIC} = {{{nl}\tcolor = rgb {{ {COLOR[0]} {COLOR[1]} {COLOR[2]} }}{nl}'
             f'\tcolor_ui = rgb {{ {COLOR_UI[0]} {COLOR_UI[1]} {COLOR_UI[2]} }}{nl}}}{nl}')
    pat = re.compile(rf'(# WiF: Japan after New Asian Hegemon[^\n]*\n)?^{COSMETIC} = \{{.*?^\}}\r?\n', re.M | re.S)
    if pat.search(text):
        text = pat.sub(lambda m: block, text)
    else:
        text = text.rstrip('\r\n') + nl + nl + block
    open(path, 'wb').write(text.encode('utf-8'))
    print('cosmetic.txt updated')


def gen_flags():
    # Japan keeps its flag: copy vanilla's per-ideology JAP flags. There is no
    # plain JAP.tga in vanilla; the fallback is the neutrality flag.
    for sub in ['', 'medium', 'small']:
        src_dir = os.path.join(GAME, 'gfx', 'flags', sub)
        dst_dir = p('gfx', 'flags', sub) if sub else p('gfx', 'flags')
        os.makedirs(dst_dir, exist_ok=True)
        for ide in IDEOLOGIES:
            shutil.copyfile(os.path.join(src_dir, f'JAP_{ide}.tga'), os.path.join(dst_dir, f'{COSMETIC}_{ide}.tga'))
        shutil.copyfile(os.path.join(src_dir, 'JAP_neutrality.tga'), os.path.join(dst_dir, f'{COSMETIC}.tga'))
    print('flags copied')


