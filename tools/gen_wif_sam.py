def vanilla_override():
    """Same-filename copy of vanilla sam_missile.txt with production switched off."""
    src = os.path.join(GAME, 'common', 'units', 'equipment', 'sam_missile.txt')
    with open(src, encoding='utf-8-sig') as f:
        t = f.read().replace('\r\n', '\n')
    m = re.search(r'\n\t\tcan_be_produced = \{', t)
    assert m, 'can_be_produced'
    i, d = m.end(), 1
    while d:
        d += {'{': 1, '}': -1}.get(t[i], 0)
        i += 1
    t = t[:m.start()] + '\n\t\tcan_be_produced = { always = no } # WiF: retired, see wif_sam_battery' + t[i:]
    n = t.count('\t\tis_buildable = yes')
    assert n == 2, n
    t = t.replace('\t\tis_buildable = yes', '\t\tis_buildable = no # WiF: retired')
    head = ('# GENERATED by tools/gen_wif_sam.py - WiF copy of vanilla\n'
            '# common/units/equipment/sam_missile.txt (same filename = override). Vanilla SAMs\n'
            '# can no longer be produced; existing stock still deploys. Re-run after a game update.\n\n')
    path = os.path.join(MOD, 'common', 'units', 'equipment', 'sam_missile.txt')
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write((head + t).replace('\n', '\r\n'))
    print('wrote common/units/equipment/sam_missile.txt')


