def op_numbers(g):
    """RNG scope: temp wif_rng_need / wif_rng_cost / wif_rng_mult for group g's current plan."""
    o = []
    for i, (key, _, need, c, who) in OPS.items():
        o.append(f'{"if" if i == 1 else "else_if"} = {{ limit = {{ check_variable = {{ wif_rng_{g}_plan = {i} }} }} '
                 f'set_temp_variable = {{ wif_rng_need = {need} }} set_temp_variable = {{ wif_rng_cost = {c} }} }}')
    o.append('set_temp_variable = { wif_rng_mult = 1 }')
    for groups, ops, kind, val, trig in OP_MODS:
        if groups != 'all' and groups != g:
            continue
        opl = list(OPS) if ops == 'all' else ops
        cond = f'OR = {{ {" ".join(f"check_variable = {{ wif_rng_{g}_plan = {i} }}" for i in opl)} }}'
        if kind == 'need':
            eff = f'add_to_temp_variable = {{ wif_rng_need = {val} }}'
        elif kind == 'cost':
            eff = f'multiply_temp_variable = {{ wif_rng_cost = {val} }}'
        else:
            eff = f'multiply_temp_variable = {{ wif_rng_mult = {val} }}'
        o.append(f'if = {{ limit = {{ {cond} {trig} }} {eff} }}')
    o.append('clamp_temp_variable = { var = wif_rng_need min = 5 }')
    return '\n'.join(o)


