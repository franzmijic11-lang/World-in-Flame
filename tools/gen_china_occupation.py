def p(*a):
    return os.path.join(MOD, *a)


def write(rel, text, bom=False, crlf=True):
    path = p(rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if crlf:
        text = text.replace('\r\n', '\n').replace('\n', '\r\n')
    with open(path, 'w', encoding='utf-8-sig' if bom else 'utf-8', newline='') as f:
        f.write(text)
    print('wrote', rel)


def cost(days):
    w = days / 7
    return str(int(round(w))) if abs(w - round(w)) < 1e-9 else f'{math.ceil(w * 1000) / 1000:.3f}'


def indent(s, n):
    return '\n'.join(('\t' * n + l) if l else l for l in s.split('\n'))


def j(*xs):
    return '\n'.join(x for x in xs if x)


def block(head, body):
    return j(f'{head} = {{', indent(body, 1), '}')


def tt(key, text, body=''):
    TT[key] = text
    return j(f'custom_effect_tooltip = {key}', block('hidden_effect', body)) if body else f'custom_effect_tooltip = {key}'


