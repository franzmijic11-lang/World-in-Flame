def tiers_update(family, n, var, thresholds, scope_note=''):
    """Effect: swap to the right tier idea of a family given a variable and thresholds."""
    o = [f'set_temp_variable = {{ wif_t_tier = 1 }}']
    for i, th in enumerate(thresholds[1:], 2):
        o.append(f'if = {{ limit = {{ check_variable = {{ {var} > {th - 0.001} }} }} set_temp_variable = {{ wif_t_tier = {i} }} }}')
    for i in range(1, n + 1):
        o.append(f'if = {{ limit = {{ check_variable = {{ wif_t_tier = {i} }} NOT = {{ has_idea = {family}_{i} }} }} '
                 + ' '.join(f'if = {{ limit = {{ has_idea = {family}_{k} }} remove_ideas = {family}_{k} }}' for k in range(1, n + 1) if k != i)
                 + f' add_ideas = {family}_{i} }}')
    return '\n'.join(o)


