def icon_names():
    names = set()
    for root in (GAME, MOD):
        for fn in glob.glob(os.path.join(root, 'interface', '*.gfx')):
            names |= set(re.findall(r'name\s*=\s*"?(GFX_[A-Za-z0-9_]+)', open(fn, encoding='utf-8', errors='ignore').read()))
    return names


def icon_for(fid, prefix, names):
    if fid in ICON_OVERRIDE and ICON_OVERRIDE[fid] in names:
        return ICON_OVERRIDE[fid]
    key = fid[len(prefix):]
    for rx, ic in ICON_RULES:
        if re.search(rx, key) and ic in names:
            return ic
    return 'GFX_goal_generic_national_unity'


def load(snap):
    m = json.load(open(p('tools', snap), encoding='utf-8'))
    return m.get('data', m)


def gen_tree(tag, prefix, tree, snap, rewards, names):
    m = load(snap)
    by_id = {f['id']: f for f in m['focuses']}
    keys = {f['fid'][len(prefix):] for f in m['focuses']}
    missing = sorted(k for k in keys if k not in rewards)
    assert not missing, f'{tree}: no reward for {missing}'
    extra = sorted(set(rewards) - keys)
    if extra:
        print(f'NOTE {tree}: rewards for focuses no longer in the planner (ignored):', extra)
    maxy = max(f['y'] for f in m['focuses'])
    o = [HEADER.rstrip('\n'), f'# Layout from the Focus Tree Planner (tools/{snap}). Loaded by Japan\'s dictated peace.', '',
         'focus_tree = {', f'\tid = {tree}', '', '\tcountry = {', '\t\tfactor = 0', '\t}', '',
         '\tdefault = no', '\treset_on_civilwar = no',
         f'\tcontinuous_focus_position = {{ x = 50 y = {(maxy + 2) * 130} }}', '']
    for f in sorted(m['focuses'], key=lambda f: (f['y'], f['x'])):
        fid = f['fid']
        k = fid[len(prefix):]
        o += ['\tfocus = {', f'\t\tid = {fid}', f'\t\ticon = {icon_for(fid, prefix, names)}']
        if f['pre']:
            ids = [by_id[i]['fid'] for i in f['pre']]
            if f.get('any'):
                o.append('\t\tprerequisite = { ' + ' '.join(f'focus = {i}' for i in ids) + ' }')
            else:
                o += [f'\t\tprerequisite = {{ focus = {i} }}' for i in ids]
        if f['mx']:
            o.append('\t\tmutually_exclusive = { ' + ' '.join(f'focus = {by_id[i]["fid"]}' for i in f['mx']) + ' }')
        o += [f'\t\tx = {f["x"]}', f'\t\ty = {f["y"]}', f'\t\tcost = {cost(f["days"])}']
        avail = 'always = no' if f.get('auto') else AVAILABLE.get(fid)
        if avail:
            o += ['\t\tavailable = {', f'\t\t\t{avail}', '\t\t}']
        o.append(f'\t\tai_will_do = {{ factor = {AI.get(fid, 10)} }}')
        o.append(f'\t\tsearch_filters = {{ {FILTER.get(f["branch"], "FOCUS_FILTER_POLITICAL")} }}')
        o += ['\t\tcompletion_reward = {', indent(j(rewards[k], refresh()), 3), '\t\t}', '\t}', '']
    o += ['}', '']
    write(f'common/national_focus/{tree}.txt', '\n'.join(o))
    return m


def esc(s):
    return s.replace('"', '\\"').replace('\n', '\\n')


HDR = re.compile(r"^(Effect:|AUTO-COMPLETES|THIS IS|[A-Z][A-Z' ]{3,}[A-Z](?: \(|:| -|\)))")


def flavour(desc):
    paras = desc.split('\n\n')
    keep = []
    for para in paras:
        para = re.sub(r'^AUTO-COMPLETES \(consequence\)\.\s*', '', para)
        para = re.sub(r'^(Not before \d+ \([^)]*\)\.|Available (?:once|only if)[^.]*\.|Only possible while[^.]*\.)\s*', '', para)
        if HDR.match(para) or not para.strip():
            if keep:
                break
            continue
        keep.append(para.strip())
    return '\n\n'.join(keep)


